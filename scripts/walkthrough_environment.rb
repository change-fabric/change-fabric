# frozen_string_literal: true

require 'erb'
require 'fileutils'
require 'json'

# The environment scene kind: a simulated, neutral desktop (browser,
# file explorer, text editor, terminal, elevation prompt, services list)
# rendered from the desktop kit in skills/prototype/fixtures/desktop/ and the
# scene's seed. Nothing on a real machine is touched. The kit owns the chrome
# and the fixed ids; the project owns the content (file names, config text,
# transcript lines, service names, the page shown in a browser window).
#
# Like a prototype message screen, the screen file is generated once (this
# script's CLI) and validation flags drift: a screen whose ids differ from
# what the kit would write, or one that is merely stale.
module WalkthroughEnvironment
  KIND = 'environment'
  WINDOW_TYPES = %w[browser file-explorer text-editor terminal elevation-prompt services-list].freeze
  SPEC_FIELDS = %w[open focus slots].freeze
  SEED_KEYS = %w[clock windows files services terminal editor downloads].freeze
  ID_RE = /\A[a-z0-9][a-z0-9-]*\z/
  GENERATED = '<!-- generated by walkthrough_environment.rb from the storyboard; edit the scene or seed, not this file -->'

  module_function

  def environment?(scene) = scene['kind'] == KIND

  def kit_roots
    [ File.expand_path('../skills/prototype/fixtures/desktop', __dir__),
      File.join(Dir.home, '.claude', 'skills', 'cf:prototype', 'fixtures', 'desktop'),
      File.join(Dir.home, '.config', 'opencode', 'skills', 'cf-prototype', 'fixtures', 'desktop') ]
  end

  def kit_dir = kit_roots.find { |r| File.file?(File.join(r, 'VERSION')) } || raise(ArgumentError, 'desktop kit not found')

  def kit(name) = File.read(File.join(kit_dir, name))

  # The kit version; it feeds every environment scene's frames_key.
  def version = kit('VERSION').strip

  def slug(text) = text.to_s.downcase.gsub(/[^a-z0-9]+/, '-').gsub(/\A-|-\z/, '')

  # -- validation ------------------------------------------------------------

  def errors(scene, root)
    spec = scene['environment'] || {}
    return [ 'environment must be an object' ] unless spec.is_a?(Hash)

    errs = (spec.keys - SPEC_FIELDS).empty? ? [] : [ "environment has unknown keys: #{(spec.keys - SPEC_FIELDS).join(', ')}" ]
    errs << 'an environment scene needs screen.html (a generated file)' if scene.dig('screen', 'html').to_s.empty?
    seed_path = scene.dig('store', 'seed')
    return errs << 'an environment scene needs store.seed' if seed_path.to_s.empty?
    return errs << 'store.seed must be inside the walkthrough directory' if seed_path.start_with?('/') || seed_path.split('/').include?('..')
    return errs if root.nil?
    return errs << "store.seed #{seed_path} does not exist" unless File.file?(File.join(root, seed_path))

    seed = JSON.parse(File.read(File.join(root, seed_path)))
    errs.concat(seed_errors(seed))
    return errs unless errs.empty?

    errs.concat(spec_errors(spec, seed, root))
    errs.empty? ? drift_errors(scene, root) : errs
  rescue JSON::ParserError => e
    [ "store.seed is not valid JSON: #{e.message.lines.first.strip}" ]
  end

  def seed_errors(seed)
    return [ 'seed must be an object' ] unless seed.is_a?(Hash)

    errs = []
    errs << 'seed.clock must be a string' if seed.key?('clock') && !seed['clock'].is_a?(String)
    windows = seed['windows']
    return errs << 'seed.windows must be a non-empty list' unless windows.is_a?(Array) && !windows.empty? && windows.all?(Hash)

    ids = windows.map { |w| w['id'] }
    ids.tally.each { |id, n| errs << "seed window id #{id.inspect} is not unique" if n > 1 }
    windows.each { |w| errs.concat(window_errors(w, seed, ids)) }
    errs.concat(list_errors(seed))
  end

  def window_errors(win, seed, ids)
    label = "seed window #{win['id'].inspect}"
    errs = []
    errs << "#{label}: id must match [a-z0-9][a-z0-9-]*" unless win['id'].to_s.match?(ID_RE)
    errs << "#{label}: type must be one of #{WINDOW_TYPES.join(', ')}" unless WINDOW_TYPES.include?(win['type'])
    errs << "#{label}: title is required" if win['title'].to_s.strip.empty?
    %w[x y w h].each { |k| errs << "#{label}: #{k} must be a non-negative integer" unless win[k].is_a?(Integer) && win[k] >= 0 }
    case win['type']
    when 'text-editor'
      docs = Array(seed.dig('editor', 'documents')).map { |d| d['path'] }
      errs << "#{label}: document must be a path in editor.documents" unless docs.include?(win['document'])
    when 'elevation-prompt'
      errs << "#{label}: app is required" if win['app'].to_s.strip.empty?
      errs << "#{label}: then must name a window" if win.key?('then') && !ids.include?(win['then'])
    when 'file-explorer'
      errs << "#{label}: folder is required" if win['folder'].to_s.empty?
      opens = win['opens'] || {}
      errs << "#{label}: opens maps file names to window ids" unless opens.is_a?(Hash) && opens.values.all? { |v| ids.include?(v) }
    end
    errs
  end

  def list_errors(seed)
    errs = []
    Array(seed['files']).each { |f| errs << 'seed.files entries need a path' unless f.is_a?(Hash) && f['path'].is_a?(String) }
    Array(seed['services']).each do |s|
      errs << 'seed.services entries need name, status, startup strings' unless s.is_a?(Hash) && %w[name status startup].all? { |k| s[k].is_a?(String) }
    end
    Array(seed['downloads']).each do |d|
      ok = d.is_a?(Hash) && d['name'].is_a?(String) && %w[pending complete].include?(d['state'] || 'complete')
      errs << 'seed.downloads entries need a name and a state of pending or complete' unless ok
    end
    Array(seed.dig('terminal', 'transcript')).each do |line|
      ok = line.is_a?(Hash) && line['text'].is_a?(String) && (!line.key?('after_ms') || line['after_ms'].is_a?(Integer) && line['after_ms'] >= 0)
      errs << 'seed.terminal.transcript entries need text and a non-negative integer after_ms' unless ok
    end
    Array(seed.dig('editor', 'documents')).each do |d|
      ok = d.is_a?(Hash) && d['path'].is_a?(String) && d['text'].is_a?(String) && (!d.key?('caret_after') || d['caret_after'].is_a?(String))
      errs << 'seed.editor.documents entries need path and text strings (and an optional caret_after string)' unless ok
    end
    errs
  end

  def spec_errors(spec, seed, root)
    ids = seed['windows'].map { |w| w['id'] }
    errs = []
    open = spec['open']
    errs << "environment.open names unknown windows: #{(Array(open) - ids).join(', ')}" if open && !(Array(open) - ids).empty?
    errs << "environment.focus #{spec['focus'].inspect} must be an open window" if spec['focus'] && !open_ids(spec, seed).include?(spec['focus'])
    slots = spec['slots'] || {}
    return errs << 'environment.slots maps slot names to files' unless slots.is_a?(Hash)

    browsers = seed['windows'].select { |w| w['type'] == 'browser' }.map { |w| "#{w['id']}-content" }
    slots.each do |name, file|
      errs << "environment.slots.#{name} is not a browser content slot (#{browsers.join(', ')})" unless browsers.include?(name)
      if file.to_s.start_with?('/') || file.to_s.split('/').include?('..')
        errs << "environment.slots.#{name} must be inside the walkthrough directory"
      elsif !File.file?(File.join(root, file.to_s))
        errs << "environment.slots.#{name}: #{file} does not exist"
      end
    end
    errs
  end

  # Ids in the committed screen must be exactly the kit's; anything else in
  # the file differing only means it is stale.
  def drift_errors(scene, root)
    path = File.join(root, scene.dig('screen', 'html'))
    want = screen(scene, root)
    return [ "#{scene.dig('screen', 'html')} does not exist; run walkthrough_environment.rb on the storyboard" ] unless File.file?(path)

    have = File.read(path)
    return [] if have == want

    missing = ids_in(want) - ids_in(have)
    extra = ids_in(have) - ids_in(want)
    unless missing.empty? && extra.empty?
      return [ "#{scene.dig('screen', 'html')} drifted from the desktop kit ids (missing: #{missing.join(', ')}; extra: #{extra.join(', ')})" ]
    end

    [ "#{scene.dig('screen', 'html')} is stale; run walkthrough_environment.rb on the storyboard" ]
  end

  def ids_in(html) = html.scan(/\sid="([^"]+)"/).flatten.uniq

  # -- rendering ---------------------------------------------------------------

  def esc(text) = ERB::Util.html_escape(text.to_s)

  def fill(text, values) = text.gsub(/\{\{(\w+)\}\}/) { values.fetch(Regexp.last_match(1)) }

  def template(name) = kit(File.join('templates', name))

  def open_ids(spec, seed) = spec['open'] ? Array(spec['open']) : seed['windows'].map { |w| w['id'] }

  def seed_for(scene, root) = JSON.parse(File.read(File.join(root, scene.dig('store', 'seed'))))

  # The full screen file for an environment scene.
  def screen(scene, root)
    spec = scene['environment'] || {}
    seed = seed_for(scene, root)
    open = open_ids(spec, seed)
    focus = spec['focus'] || open.last
    windows = seed['windows'].map { |w| window_html(w, seed, spec, root, open: open.include?(w['id']), focus: w['id'] == focus) }
    tasks = seed['windows'].map do |w|
      %(<button id="task-#{w['id']}" class="cfd-task" type="button" data-cfd-task="#{w['id']}"#{open.include?(w['id']) ? '' : ' hidden'}>#{esc(w['title'])}</button>)
    end
    out = scene.dig('screen', 'html')
    tokens = File.file?(File.join(root, File.dirname(out), 'tokens.css')) ? %(<link rel="stylesheet" href="tokens.css">\n) : ''
    html = fill(template('page.html'), 'title' => esc(scene['title'] || 'Desktop'), 'tokens' => tokens, 'css' => kit('desktop.css'),
                                       'windows' => windows.join("\n"), 'tasks' => tasks.join("\n"), 'clock' => esc(seed['clock'] || '9:41'),
                                       'script' => kit('wm.js'))
    "#{GENERATED}\n<!-- cf desktop kit v#{version} -->\n#{html}"
  end

  def window_html(win, seed, spec, root, open:, focus:)
    body = send("#{win['type'].tr('-', '_')}_body", win, seed, spec, root)
    fill(template('window.html'), 'id' => win['id'], 'type' => win['type'], 'title' => esc(win['title']), 'focus' => focus ? ' cfd-focus' : '',
                                  'attrs' => window_attrs(win), 'x' => win['x'].to_s, 'y' => win['y'].to_s, 'w' => win['w'].to_s,
                                  'h' => win['h'].to_s, 'hidden' => open ? '' : ' hidden', 'body' => body)
  end

  def window_attrs(win)
    win['type'] == 'file-explorer' && win['extract_to'] ? %( data-cfd-extract-to="#{esc(win['extract_to'])}") : ''
  end

  def browser_body(win, seed, spec, root)
    downloads = Array(seed['downloads'])
    items = downloads.map do |d|
      pending = (d['state'] || 'complete') == 'pending'
      %(<span id="#{win['id']}-download-#{slug(d['name'])}" class="cfd-dl" data-cfd-dl="#{esc(d['name'])}"#{pending ? ' hidden' : ''}>) +
        %(<span>#{esc(d['name'])}</span><span class="cfd-dl-state">#{pending ? '0%' : esc(d['size'] || 'Done')}</span></span>)
    end
    list = downloads.map { |d| "<li>#{esc(d['name'])}</li>" }
    slot = (spec['slots'] || {})["#{win['id']}-content"]
    content = slot ? File.read(File.join(root, slot)) : ''
    all_pending = downloads.all? { |d| d['state'] == 'pending' }
    fill(template('browser.html'), 'id' => win['id'], 'tab' => esc(win['tab'] || win['title']), 'url' => esc(win['url']), 'content' => content,
                                   'bar_hidden' => all_pending ? ' hidden' : '', 'downloads' => items.join, 'list' => list.join)
  end

  def folder_of(path) = path.to_s.sub(/[\\\/][^\\\/]*\z/, '')

  def base_of(path) = path.to_s[/[^\\\/]*\z/]

  def file_rows(win, seed, folder, prefix)
    Array(seed['files']).select { |f| folder_of(f['path']).casecmp?(folder.to_s) }.map do |f|
      name = base_of(f['path'])
      opens = (win['opens'] || {})[name]
      %(<li id="#{win['id']}-#{prefix}-#{slug(name)}" class="cfd-file"#{opens ? %( data-cfd-open="#{opens}") : ''}>) +
        %(<span>#{esc(name)}</span><span class="cfd-kind">#{esc(f['kind'] || kind_of(name))}</span><span class="cfd-size">#{esc(f['size'])}</span></li>)
    end.join
  end

  def kind_of(name)
    return 'Folder' unless name.include?('.')

    "#{File.extname(name).delete('.').upcase} file"
  end

  def file_explorer_body(win, seed, _spec, _root)
    folders = [ win['folder'], win['extract_to'] ].compact.uniq
    tree = folders.map { |f| %(<li data-path="#{esc(f)}"#{f == win['folder'] ? ' class="cfd-here"' : ''}>#{esc(f)}</li>) }
    extract = win['extract_to'] ? %(<button id="#{win['id']}-extract" class="cfd-btn" type="button" data-cfd-extract="#{win['id']}">Extract all</button>) : ''
    fill(template('file-explorer.html'), 'id' => win['id'], 'tree' => tree.join, 'folder' => esc(win['folder']), 'extract' => extract,
                                         'files' => file_rows(win, seed, win['folder'], 'file'),
                                         'xfiles' => win['extract_to'] ? file_rows(win, seed, win['extract_to'], 'xfile') : '')
  end

  def text_editor_body(win, seed, _spec, _root)
    doc = Array(seed.dig('editor', 'documents')).find { |d| d['path'] == win['document'] }
    caret = doc['caret_after'] ? %( data-cfd-caret="#{esc(doc['caret_after'])}") : ''
    fill(template('text-editor.html'), 'id' => win['id'], 'title' => esc(win['title']), 'text' => esc(doc['text']), 'path' => esc(doc['path']),
                                       'caret' => caret)
  end

  def terminal_body(win, seed, _spec, _root)
    lines = Array(seed.dig('terminal', 'transcript')).each_with_index.map do |line, i|
      svc = line['service'] ? %( data-cfd-service="#{slug(line['service'])}" data-cfd-status="#{esc(line['status'])}") : ''
      %(<div id="#{win['id']}-line-#{i + 1}" data-after="#{line['after_ms'] || 0}"#{svc} hidden>#{esc(line['text'])}</div>)
    end
    fill(template('terminal.html'), 'id' => win['id'], 'lines' => lines.join)
  end

  def elevation_prompt_body(win, _seed, _spec, _root)
    fill(template('elevation-prompt.html'), 'id' => win['id'], 'app' => esc(win['app']), 'publisher' => esc(win['publisher'] || 'Unknown publisher'),
                                            'then' => esc(win['then']))
  end

  def services_list_body(win, seed, _spec, _root)
    rows = Array(seed['services']).map do |s|
      key = slug(s['name'])
      running = s['status'] == 'Running' ? ' class="cfd-running"' : ''
      %(<tr id="#{win['id']}-svc-#{key}"><td>#{esc(s['name'])}</td><td id="#{win['id']}-svc-#{key}-status" data-cfd-svc="#{key}"#{running}>) +
        %(#{esc(s['status'])}</td><td>#{esc(s['startup'])}</td></tr>)
    end
    fill(template('services-list.html'), 'id' => win['id'], 'rows' => rows.join)
  end

  # Writes every environment screen; returns the paths written.
  def write_screens(board, root)
    Array(board['scenes']).select { |s| environment?(s) && s.dig('screen', 'html') }.map do |scene|
      out = scene.dig('screen', 'html')
      FileUtils.mkdir_p(File.dirname(File.join(root, out)))
      File.write(File.join(root, out), screen(scene, root))
      out
    end
  end

  # The ASSUMPTIONS.md simulated UI line.
  def simulated_line(scene, root = nil)
    types = begin
      root ? ": #{seed_for(scene, root)['windows'].map { |w| w['type'] }.uniq.join(', ')}" : ''
    rescue StandardError
      ''
    end
    "- #{scene['id']}: simulated desktop environment (neutral desktop kit v#{version}#{types}); " \
      'no real machine, file, download, or service is touched'
  end
end

if __FILE__ == $PROGRAM_NAME
  path = ARGV[0] || abort('usage: walkthrough_environment.rb walkthrough/<slug>/storyboard.json')
  root = File.dirname(File.expand_path(path))
  WalkthroughEnvironment.write_screens(JSON.parse(File.read(path)), root).each { |out| puts "wrote #{out}" }
end
