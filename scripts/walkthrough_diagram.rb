# frozen_string_literal: true

require 'digest'
require 'fileutils'
require 'json'
require_relative 'diagram_palette'
require_relative 'prototype_ux_lint'

# Diagram scenes for cf:walkthrough: a full-frame React Flow diagram built and
# moved on screen under the capture clock. The storyboard carries a `diagram`
# block (nodes, edges, which start visible, and timed steps); this module
# validates it and generates the self-contained screen file the capture
# treats like any other prototype screen.
#
# xyflow is vendored, not fetched, for the same reason axe-core is (see
# scripts/change_lane_a11y.rb): a diagram scene must render the same frames
# every time, and a library pulled at capture time could change underneath a
# cached scene without a line of this repo changing. The bundle under
# scripts/vendor/xyflow is rebuilt reproducibly by scripts/xyflow_vendor.rb
# inside the pinned Node image, and `--check` confirms a rebuild matches the
# sha256 below. Upgrading means bumping the version in the build inputs and
# here, rebuilding, and committing the new file and sha on purpose; the new
# sha invalidates every cached diagram scene by design.
module WalkthroughDiagram
  XYFLOW_VERSION = '12.12.1'
  XYFLOW_BUNDLE = File.join(__dir__, 'vendor', 'xyflow', "xyflow-#{XYFLOW_VERSION}.min.js")
  XYFLOW_SHA256 = 'c459e26cdb12eea049b16060a2c18938df9c417bc5f357902e7d4a3f9c5c86aa'
  RUNTIME = File.join(__dir__, 'vendor', 'xyflow', 'cf_diagram_runtime.js')

  KIND = 'diagram'
  GENERATED = '<!-- generated by walkthrough_diagram.rb from the storyboard; edit the scene, not this file -->'
  ID_RE = /\A[a-z0-9][a-z0-9-]*\z/
  # cf:diagram's caps: past this a viewer stops following the picture.
  MAX_NODES = 12
  MAX_EDGES = 16
  ENGINES = %w[dagre manual].freeze
  DIRECTIONS = %w[TB LR BT RL].freeze
  ZOOM = (0.2..3.0)
  PADDING = (0.0..1.0)
  SPEC_FIELDS = %w[layout nodes edges initial steps].freeze
  # Ops that act on one or more ids (`id` or `ids`), and the kinds of id each
  # may name. add_node fades in nodes and the edges that come with them.
  ID_OPS = { 'add_node' => %i[node edge], 'remove' => %i[node edge], 'connect' => %i[edge], 'highlight' => %i[node edge],
             'dim' => %i[node edge], 'unhighlight' => %i[node edge], 'pulse_edge' => %i[edge], 'flow' => %i[edge] }.freeze
  # flow: how many dots may ride one edge at once.
  FLOW_COUNT = (1..8)
  DIAGRAM_OPS = (ID_OPS.keys + %w[move label fit_view zoom_to focus]).freeze
  # The screen's colours, as --cf-* variables, when the walkthrough has no
  # tokens.css. With one, each variable takes the cf:diagram palette role
  # named in PALETTE_ROLES, resolved by DiagramPalette from the light theme.
  PALETTE = { 'surface' => '#ffffff', 'node' => '#f8fafc', 'line' => '#64748b', 'rule' => '#cbd5e1', 'text' => '#0f172a',
              'muted' => '#475569', 'accent' => '#1d4ed8', 'accent-tint' => '#dbeafe' }.freeze
  PALETTE_ROLES = { 'surface' => '--bg', 'node' => '--surface', 'line' => '--line', 'rule' => '--rule', 'text' => '--ink',
                    'muted' => '--muted', 'accent' => '--accent', 'accent-tint' => '--accent-tint' }.freeze
  # A node's `role` picks its border, fill, and text from the palette.
  NODE_ROLES = %w[default accent muted].freeze
  # Pairs DiagramPalette does not check but a diagram node draws: label text
  # on each node fill.
  NODE_CONTRAST = [ %w[--ink --accent-tint], %w[--muted --bg] ].freeze

  module_function

  def diagram?(scene) = scene['kind'] == KIND

  def runtime_sha256 = Digest::SHA256.file(RUNTIME).hexdigest

  # frames_key material: a new bundle or runtime invalidates cached frames.
  def key_material = { xyflow: XYFLOW_SHA256, diagram_runtime: runtime_sha256 }

  # -- validation ------------------------------------------------------------

  def errors(scene, root, board: {})
    spec = scene['diagram']
    return [ 'a diagram scene needs a diagram object' ] unless spec.is_a?(Hash)

    errs = spec_errors(spec, PrototypeCapture.scene_duration(scene))
    errs << 'a diagram scene needs screen.html (a generated file)' if scene.dig('screen', 'html').to_s.empty?
    return errs unless errs.empty? && root

    palette_errors(root) + drift_errors(scene, root, board)
  end

  def spec_errors(spec, duration_ms)
    errs = (spec.keys - SPEC_FIELDS).empty? ? [] : [ "diagram has unknown keys: #{(spec.keys - SPEC_FIELDS).join(', ')}" ]
    errs.concat(layout_errors(spec['layout']))
    nodes = list(spec, 'nodes')
    edges = list(spec, 'edges')
    return errs << 'diagram.nodes and diagram.edges must be lists of objects' unless nodes && edges

    errs << "diagram has #{nodes.size} nodes; the cap is #{MAX_NODES}" if nodes.size > MAX_NODES
    errs << "diagram has #{edges.size} edges; the cap is #{MAX_EDGES}" if edges.size > MAX_EDGES
    errs << 'diagram.nodes must not be empty' if nodes.empty?
    errs.concat(id_errors(nodes + edges))
    nodes.each { |n| errs.concat(node_errors(n)) }
    ids = { node: nodes.map { |n| n['id'] }, edge: edges.map { |e| e['id'] } }
    edges.each { |e| errs.concat(edge_errors(e, ids[:node])) }
    initial = spec['initial'] || []
    if initial.is_a?(Array)
      unknown = initial - ids.values.flatten
      errs << "diagram.initial names unknown ids: #{unknown.join(', ')}" unless unknown.empty?
    else
      errs << 'diagram.initial must be a list of ids'
    end
    errs.concat(steps_errors(spec['steps'] || [], ids, duration_ms))
  end

  def list(spec, key)
    value = spec[key] || []
    value.is_a?(Array) && value.all?(Hash) ? value : nil
  end

  def layout_errors(layout)
    return [] if layout.nil?
    return [ 'diagram.layout must be an object' ] unless layout.is_a?(Hash)

    errs = []
    errs << "diagram.layout has unknown keys: #{(layout.keys - %w[engine direction]).join(', ')}" unless (layout.keys - %w[engine direction]).empty?
    errs << "diagram.layout.engine must be one of #{ENGINES.join(', ')}" if layout.key?('engine') && !ENGINES.include?(layout['engine'])
    errs << "diagram.layout.direction must be one of #{DIRECTIONS.join(', ')}" if layout.key?('direction') && !DIRECTIONS.include?(layout['direction'])
    errs
  end

  # Nodes and edges share one id space: steps name either by id.
  def id_errors(items)
    errs = items.map { |i| i['id'] }.reject { |id| id.to_s.match?(ID_RE) }.map { |id| "diagram id #{id.inspect} must match [a-z0-9][a-z0-9-]*" }
    items.map { |i| i['id'] }.tally.each { |id, n| errs << "diagram id #{id.inspect} is not unique across nodes and edges" if n > 1 }
    errs
  end

  def node_errors(node)
    label = "diagram node #{node['id'].inspect}"
    errs = []
    errs << "#{label}: label must be a non-empty string" unless node['label'].is_a?(String) && !node['label'].strip.empty?
    errs << "#{label}: role must be one of #{NODE_ROLES.join(', ')}" if node.key?('role') && !NODE_ROLES.include?(node['role'])
    errs << "#{label}: position must be { x, y } numbers" if node.key?('position') && !point?(node['position'])
    errs
  end

  def edge_errors(edge, node_ids)
    label = "diagram edge #{edge['id'].inspect}"
    errs = %w[source target].filter_map { |k| "#{label}: #{k} #{edge[k].inspect} is not a node" unless node_ids.include?(edge[k]) }
    errs << "#{label}: label must be a string" if edge.key?('label') && !edge['label'].is_a?(String)
    errs
  end

  def point?(value) = value.is_a?(Hash) && value.keys.sort == %w[x y] && value.values.all?(Numeric)

  def steps_errors(steps, ids, duration_ms)
    return [ 'diagram.steps must be a list of objects' ] unless steps.is_a?(Array) && steps.all?(Hash)

    last = -1
    steps.each_with_index.flat_map do |step, i|
      errs = []
      t = step['t_ms']
      if !t.is_a?(Integer) || t.negative?
        errs << 't_ms must be a non-negative integer'
      elsif t < last
        errs << 't_ms must be non-decreasing'
      elsif t >= duration_ms
        errs << "t_ms #{t} must be below the scene duration (#{duration_ms} ms)"
      else
        last = t
      end
      errs.concat(op_errors(step, ids))
      errs.map { |e| "diagram step #{i}: #{e}" }
    end
  end

  def op_errors(step, ids)
    op = step['op']
    return [ "op #{op.inspect} must be one of #{DIAGRAM_OPS.join(', ')}" ] unless DIAGRAM_OPS.include?(op)

    errs = []
    errs << 'duration must be a non-negative integer' if step.key?('duration') && !(step['duration'].is_a?(Integer) && !step['duration'].negative?)
    errs.concat(flow_errors(step)) if op == 'flow'
    return errs.concat(id_op_errors(step, ids, ID_OPS[op])) if ID_OPS.key?(op)

    case op
    when 'move'
      errs.concat(ref_errors([ step['id'] ], ids, %i[node]))
      errs << 'move needs a position of { x, y } numbers' unless point?(step['position'])
    when 'label'
      errs.concat(ref_errors([ step['id'] ], ids, %i[node]))
      errs << 'label needs a text string' unless step['text'].is_a?(String)
    when 'fit_view'
      errs.concat(ref_errors(step['ids'], ids, %i[node])) if step.key?('ids')
      errs << "padding must be a number in #{PADDING.min}..#{PADDING.max}" if step.key?('padding') && !range?(step['padding'], PADDING)
    when 'zoom_to'
      errs << "zoom must be a number in #{ZOOM.min}..#{ZOOM.max}" unless range?(step['zoom'], ZOOM)
    when 'focus'
      errs.concat(ref_errors([ step['id'] ], ids, %i[node]))
      errs << "zoom must be a number in #{ZOOM.min}..#{ZOOM.max}" if step.key?('zoom') && !range?(step['zoom'], ZOOM)
    end
    errs
  end

  def flow_errors(step)
    errs = []
    errs << "count must be an integer in #{FLOW_COUNT.min}..#{FLOW_COUNT.max}" if step.key?('count') && !(step['count'].is_a?(Integer) && FLOW_COUNT.cover?(step['count']))
    errs << 'stagger must be a non-negative integer' if step.key?('stagger') && !(step['stagger'].is_a?(Integer) && !step['stagger'].negative?)
    errs << 'repeat must be a positive integer' if step.key?('repeat') && !(step['repeat'].is_a?(Integer) && step['repeat'].positive?)
    errs << 'loop must be true or false' if step.key?('loop') && ![ true, false ].include?(step['loop'])
    errs << 'flow takes loop or repeat, not both' if step['loop'] == true && step.key?('repeat')
    errs << 'duration must be positive for flow' if step['duration'] == 0
    errs
  end

  def range?(value, range) = value.is_a?(Numeric) && range.cover?(value)

  def id_op_errors(step, ids, kinds)
    return [ "#{step['op']} takes id or ids, not both" ] if step.key?('id') && step.key?('ids')

    refs = step.key?('ids') ? step['ids'] : [ step['id'] ]
    return [ "#{step['op']} needs id or a non-empty ids list" ] unless refs.is_a?(Array) && !refs.empty? && !refs.include?(nil)

    ref_errors(refs, ids, kinds)
  end

  def ref_errors(refs, ids, kinds)
    return [ 'ids must be a list of ids' ] unless refs.is_a?(Array)

    allowed = kinds.flat_map { |k| ids[k] }
    bad = refs.reject { |r| allowed.include?(r) }
    bad.empty? ? [] : [ "#{bad.map(&:inspect).join(', ')} is not a #{kinds.join(' or ')} id" ]
  end

  # A committed screen that differs from what the generator writes now.
  def drift_errors(scene, root, board = {})
    rel = scene.dig('screen', 'html')
    path = File.join(root, rel)
    return [ "#{rel} does not exist; run walkthrough_diagram.rb on the storyboard" ] unless File.file?(path)
    return [] if File.read(path) == screen(scene, root: root, board: board)

    [ "#{rel} drifted from the storyboard's diagram block; run walkthrough_diagram.rb on the storyboard (or validate --fix)" ]
  end

  # -- rendering ---------------------------------------------------------------

  # Script text inlined inside <script>; data-cf-inline tells inline_screen
  # the body is opaque code, not markup to rewrite.
  def script(body) = %(<script data-cf-inline>#{body.gsub('</script', '<\/script')}</script>)

  # Validation lets nodes, edges, and steps be omitted, but the runtime maps
  # over each, so they are written as empty lists. `<` and `>` become JSON
  # escapes so a label like "<iframe>" reaches the runtime as text instead of
  # markup inline_screen would reject or a tag that could close the script.
  def spec_json(spec)
    keep = spec.is_a?(Hash) ? spec.slice(*SPEC_FIELDS) : {}
    %w[nodes edges steps].each { |key| keep[key] ||= [] }
    JSON.pretty_generate(keep).gsub(/[<>]/) { |c| format('\\u%04x', c.ord) }
  end

  # -- palette -------------------------------------------------------------

  # The walkthrough's tokens.css, found the way its tokens_css_sha256 is.
  def tokens_path(root)
    require_relative 'walkthrough_storyboard'
    root && WalkthroughStoryboard.canonical_tokens(root)
  end

  # The --cf-* colours for a walkthrough at root: its tokens' light roles,
  # else the placeholder PALETTE.
  def palette(root)
    path = tokens_path(root)
    return PALETTE unless path

    roles = DiagramPalette.resolve(path).light
    PALETTE_ROLES.transform_values { |role| roles.fetch(role) }
  rescue DiagramPalette::Error
    PALETTE # palette_errors reports it; the screen still renders
  end

  # The light theme's contrast floors (DiagramPalette's own checks plus the
  # node fills); an unreadable token file is an error, not a silent default.
  def palette_errors(root)
    path = tokens_path(root)
    return [] unless path

    result = DiagramPalette.resolve(path)
    roles = result.light
    node = NODE_CONTRAST.filter_map do |fg, bg|
      ratio = DiagramPalette.contrast(roles[fg], roles[bg])
      "light: #{fg} on #{bg} is #{ratio.round(2)}:1, under #{DiagramPalette::TEXT_MIN}" if ratio < DiagramPalette::TEXT_MIN
    end
    (result.warnings.grep(/\Alight:/) + node).map { |w| "diagram palette from #{path}: #{w}" }
  rescue DiagramPalette::Error => e
    [ "diagram palette from #{path}: #{e.message}" ]
  end

  def palette_css(colors) = ":root { #{colors.map { |k, v| "--cf-#{k}: #{v};" }.join(' ')} }"

  # Where the scene sits in the frame: the bottom inset keeps the camera's
  # fit and focus targets above the caption band players draw cues in.
  def frame(board)
    viewport = PrototypeCapture::DEFAULT_VIEWPORT.merge((board || {})['viewport'] || {})
    { 'bottom_inset' => (viewport['h'] * PrototypeUxLint::CAPTION_BAND).ceil }
  end

  # The full, self-contained screen file for a diagram scene. root locates
  # the tokens.css; board gives the viewport the caption inset comes from.
  def screen(scene, root: nil, board: {})
    title = (scene['title'] || 'Diagram').to_s.gsub(/[<>&"]/, '<' => '&lt;', '>' => '&gt;', '&' => '&amp;', '"' => '&quot;')
    <<~HTML
      #{GENERATED}
      <!-- xyflow #{XYFLOW_VERSION} sha256 #{XYFLOW_SHA256} -->
      <!doctype html>
      <html lang="en">
      <head>
      <meta charset="utf-8">
      <title>#{title}</title>
      <style>#{palette_css(palette(root))}</style>
      </head>
      <body>
      <main id="cf-diagram-root" aria-label="#{title}"></main>
      <script type="application/json" id="cf-diagram">
      #{spec_json(scene['diagram'])}
      </script>
      <script type="application/json" id="cf-diagram-frame">#{JSON.generate(frame(board))}</script>
      #{script(File.read(XYFLOW_BUNDLE))}
      #{script(File.read(RUNTIME))}
      </body>
      </html>
    HTML
  end

  # Writes each diagram scene's screen (or only `only`); returns the paths.
  def write_screens(board, root, only: nil)
    Array(board['scenes']).select { |s| diagram?(s) && s.dig('screen', 'html') && (only.nil? || s['id'] == only) }.map do |scene|
      out = scene.dig('screen', 'html')
      FileUtils.mkdir_p(File.dirname(File.join(root, out)))
      File.write(File.join(root, out), screen(scene, root: root, board: board))
      out
    end
  end

  # storyboard.md lines: the node and edge lists and a step table.
  def md(scene)
    spec = scene['diagram'] || {}
    out = Array(spec['nodes']).map { |n| "- Node `#{n['id']}`: #{n['label']}#{n['position'] ? ' (pinned)' : ''}" }
    out.concat(Array(spec['edges']).map { |e| "- Edge `#{e['id']}`: #{e['source']} -> #{e['target']}#{e['label'] ? " (#{e['label']})" : ''}" })
    out << "- Initial: #{Array(spec['initial']).join(', ')}" unless Array(spec['initial']).empty?
    steps = Array(spec['steps'])
    return out if steps.empty?

    out << '' << '| t_ms | op | target |' << '| --- | --- | --- |'
    steps.each { |s| out << "| #{s['t_ms']} | #{s['op']} | #{Array(s['ids'] || s['id']).join(', ')} |" }
    out
  end
end

if __FILE__ == $PROGRAM_NAME
  # Run as a script, this file is not yet a loaded feature; mark it so the
  # storyboard (required for the tokens lookup) does not load it twice.
  $LOADED_FEATURES << File.expand_path(__FILE__)
  args = ARGV.dup
  only = (i = args.index('--scene')) && args.slice!(i, 2)[1]
  args.delete('--fix') # writing is the fix; accepted for symmetry with validate --fix
  path = args.first || abort('usage: walkthrough_diagram.rb <storyboard.json> [--scene ID] [--fix]')
  root = File.dirname(File.expand_path(path))
  written = WalkthroughDiagram.write_screens(JSON.parse(File.read(path)), root, only: only)
  abort("no diagram scene#{" #{only}" if only} with screen.html") if written.empty?
  written.each { |out| puts "wrote #{out}" }
end
