# Diagram scenes for cf:walkthrough: a full-frame React Flow diagram built and
# moved on screen under the capture clock. The storyboard carries a `diagram`
# block (nodes, edges, which start visible, and timed steps); this module
# validates it and generates the self-contained screen file the capture
# treats like any other prototype screen.
#
# xyflow is vendored, not fetched, for the same reason axe-core is (see
# scripts/change_lane_a11y.rb): a diagram scene must render the same frames
# every time, and a library pulled at capture time could change underneath a
# cached scene without a line of this repo changing. The bundle under
# scripts/vendor/xyflow is rebuilt reproducibly by scripts/xyflow_vendor.rb
# inside the pinned Node image, and `--check` confirms a rebuild matches the
# sha256 below. Upgrading means bumping the version in the build inputs and
# here, rebuilding, and committing the new file and sha on purpose; the new
# sha invalidates every cached diagram scene by design.
module WalkthroughDiagram
  XYFLOW_VERSION = '12.12.1'
  XYFLOW_BUNDLE = File.join(__dir__, 'vendor', 'xyflow', "xyflow-#{XYFLOW_VERSION}.min.js")
  XYFLOW_SHA256 = 'c459e26cdb12eea049b16060a2c18938df9c417bc5f357902e7d4a3f9c5c86aa'
  RUNTIME = File.join(__dir__, 'vendor', 'xyflow', 'cf_diagram_runtime.js')
  # Swimlane bands, inlined only into a screen whose spec declares lanes.
  LANES_RUNTIME = File.join(__dir__, 'vendor', 'xyflow', 'cf_diagram_lanes.js')

  KIND = 'diagram'
  GENERATED = '<!-- generated by walkthrough_diagram.rb from the storyboard; edit the scene, not this file -->'
  ID_RE = /\A[a-z0-9][a-z0-9-]*\z/
  # cf:diagram's caps: past this a viewer stops following the picture.
  MAX_NODES = 12
  MAX_EDGES = 16
  ENGINES = %w[dagre manual].freeze
  DIRECTIONS = %w[TB LR BT RL].freeze
  ZOOM = (0.2..3.0)
  PADDING = (0.0..1.0)
  # layout.max_zoom: how far a fit may enlarge the picture (nodes, icons,
  # labels, and edges together). The runtime default is 1.25.
  MAX_ZOOM = (0.5..2.0)
  LAYOUT_FIELDS = %w[engine direction max_zoom].freeze
  SPEC_FIELDS = %w[layout theme lanes lane_direction nodes edges initial steps].freeze
  # Swimlanes: horizontal bands (or vertical columns) a node joins by `lane`.
  MAX_LANES = 8
  LANE_DIRECTIONS = %w[horizontal vertical].freeze
  LANE_FIELDS = %w[id label color icon icon_weight].freeze
  # A lane's band is a subtle tint of its colour over the surface, stronger
  # while highlighted; its label is drawn in the theme's text colour on both.
  LANE_TINT_SHARE = { light: 0.07, dark: 0.10 }.freeze
  LANE_HL_SHARE = 0.22
  THEMES = %w[light dark].freeze
  # Ops that act on one or more ids (`id` or `ids`), and the kinds of id each
  # may name. add_node fades in nodes and the edges that come with them.
  ID_OPS = { 'add_node' => %i[node edge lane], 'remove' => %i[node edge lane], 'connect' => %i[edge], 'highlight' => %i[node edge lane],
             'dim' => %i[node edge lane], 'unhighlight' => %i[node edge lane], 'pulse_edge' => %i[edge], 'flow' => %i[edge] }.freeze
  # flow: how many dots may ride one edge at once.
  FLOW_COUNT = (1..8)
  DIAGRAM_OPS = (ID_OPS.keys + %w[move label fit_view zoom_to focus travel]).freeze
  # The screen's colours, as --cf-* variables, when the walkthrough has no
  # tokens.css. With one, each variable takes the cf:diagram palette role
  # named in PALETTE_ROLES, resolved by DiagramPalette from the light theme.
  PALETTE = { 'surface' => '#ffffff', 'node' => '#f8fafc', 'line' => '#64748b', 'rule' => '#cbd5e1', 'text' => '#0f172a',
              'muted' => '#475569', 'accent' => '#1d4ed8', 'accent-tint' => '#dbeafe' }.freeze
  # The dark theme's placeholder, for a `theme: dark` scene with no tokens.css.
  PALETTE_DARK = { 'surface' => '#0f172a', 'node' => '#1e293b', 'line' => '#94a3b8', 'rule' => '#334155', 'text' => '#f1f5f9',
                   'muted' => '#cbd5e1', 'accent' => '#60a5fa', 'accent-tint' => '#1b2e4b' }.freeze
  PALETTE_ROLES = { 'surface' => '--bg', 'node' => '--surface', 'line' => '--line', 'rule' => '--rule', 'text' => '--ink',
                    'muted' => '--muted', 'accent' => '--accent', 'accent-tint' => '--accent-tint' }.freeze
  # A node's `role` picks its border, fill, and text from the palette.
  NODE_ROLES = %w[default accent muted].freeze
  # Pairs DiagramPalette does not check but a diagram node draws: label text
  # on each node fill.
  NODE_CONTRAST = [ %w[--ink --accent-tint], %w[--muted --bg] ].freeze
  # Item colours: a node, an edge, or a flow step may carry `color`, a named
  # role or a CSS colour. Each role takes the first of its token names the
  # walkthrough's tokens.css defines in the scene's theme, else the default
  # here. `accent` is the palette's own accent. The series roles are a
  # categorical set, for lanes that should read apart from each other.
  SERIES = 6
  ITEM_ROLE_SOURCES = {
    'success' => %w[--success --ok --positive], 'warning' => %w[--warning --warn --caution],
    'danger' => %w[--danger --error --destructive --negative]
  }.merge((1..SERIES).to_h { |i| [ "series-#{i}", %W[--series-#{i} --chart-#{i} --cat-#{i}] ] }).freeze
  ITEM_DEFAULTS = {
    light: { 'success' => '#15803d', 'warning' => '#b45309', 'danger' => '#be123c', 'series-1' => '#2563eb', 'series-2' => '#0f766e',
             'series-3' => '#b45309', 'series-4' => '#7c3aed', 'series-5' => '#be123c', 'series-6' => '#15803d' },
    dark: { 'success' => '#4ade80', 'warning' => '#fbbf24', 'danger' => '#fb7185', 'series-1' => '#60a5fa', 'series-2' => '#2dd4bf',
            'series-3' => '#fbbf24', 'series-4' => '#a78bfa', 'series-5' => '#fb7185', 'series-6' => '#4ade80' }
  }.freeze
  COLOR_ROLES = ([ 'accent' ] + ITEM_ROLE_SOURCES.keys).freeze
  CSS_COLOR = /\A(?:#\h{3}|#\h{6}|rgb\(\s*\d{1,3}\s*(?:,\s*|\s+)\d{1,3}\s*(?:,\s*|\s+)\d{1,3}\s*\))\z/
  # The halo a highlighted coloured node wears: the colour at this share over the background.
  RING_SHARE = 0.35
  # Node icons: a curated Phosphor (MIT) subset whose path data is vendored
  # by scripts/phosphor_vendor.rb, so a screen inlines each glyph it uses and
  # never fetches one. A node names an `icon` and may pick an `icon_weight`.
  ICONS_DATA = File.join(__dir__, 'vendor', 'phosphor', 'phosphor-2.1.1.json')
  ICON_WEIGHTS = %w[regular bold duotone fill].freeze

  module_function

  def diagram?(scene) = scene['kind'] == KIND

  def runtime_sha256 = Digest::SHA256.file(RUNTIME).hexdigest

  def icon_set = @icon_set ||= JSON.parse(File.read(ICONS_DATA)).freeze

  def icon_names = icon_set['icons'].keys

  # frames_key material: a new bundle or runtime invalidates cached frames.
  def key_material = { xyflow: XYFLOW_SHA256, diagram_runtime: runtime_sha256 }

  # -- validation ------------------------------------------------------------

  def errors(scene, root, board: {})
    spec = scene['diagram']
    return [ 'a diagram scene needs a diagram object' ] unless spec.is_a?(Hash)

    errs = spec_errors(spec, PrototypeCapture.scene_duration(scene))
    errs << 'a diagram scene needs screen.html (a generated file)' if scene.dig('screen', 'html').to_s.empty?
    return errs unless errs.empty? && root

    palette_errors(root, theme(spec)) + item_color_errors(spec, root) + lane_color_errors(spec, root) + drift_errors(scene, root, board)
  end

  def spec_errors(spec, duration_ms)
    errs = (spec.keys - SPEC_FIELDS).empty? ? [] : [ "diagram has unknown keys: #{(spec.keys - SPEC_FIELDS).join(', ')}" ]
    errs.concat(layout_errors(spec['layout']))
    errs << "diagram.theme must be one of #{THEMES.join(', ')}" if spec.key?('theme') && !THEMES.include?(spec['theme'])
    nodes = list(spec, 'nodes')
    edges = list(spec, 'edges')
    return errs << 'diagram.nodes and diagram.edges must be lists of objects' unless nodes && edges

    errs << "diagram has #{nodes.size} nodes; the cap is #{MAX_NODES}" if nodes.size > MAX_NODES
    errs << "diagram has #{edges.size} edges; the cap is #{MAX_EDGES}" if edges.size > MAX_EDGES
    errs << 'diagram.nodes must not be empty' if nodes.empty?
    lanes = list(spec, 'lanes')
    return errs << 'diagram.lanes must be a list of objects' unless lanes

    errs.concat(lanes_errors(spec, lanes))
    errs.concat(id_errors(nodes + edges + lanes))
    ids = { node: nodes.map { |n| n['id'] }, edge: edges.map { |e| e['id'] }, lane: lanes.map { |l| l['id'] } }
    nodes.each { |n| errs.concat(node_errors(n, ids[:lane])) }
    edges.each { |e| errs.concat(edge_errors(e, ids[:node])) }
    initial = spec['initial'] || []
    if initial.is_a?(Array)
      unknown = initial - ids.values.flatten
      errs << "diagram.initial names unknown ids: #{unknown.join(', ')}" unless unknown.empty?
    else
      errs << 'diagram.initial must be a list of ids'
    end
    errs.concat(steps_errors(spec['steps'] || [], ids, duration_ms))
  end

  def list(spec, key)
    value = spec[key] || []
    value.is_a?(Array) && value.all?(Hash) ? value : nil
  end

  def layout_errors(layout)
    return [] if layout.nil?
    return [ 'diagram.layout must be an object' ] unless layout.is_a?(Hash)

    errs = []
    errs << "diagram.layout has unknown keys: #{(layout.keys - LAYOUT_FIELDS).join(', ')}" unless (layout.keys - LAYOUT_FIELDS).empty?
    errs << "diagram.layout.engine must be one of #{ENGINES.join(', ')}" if layout.key?('engine') && !ENGINES.include?(layout['engine'])
    errs << "diagram.layout.direction must be one of #{DIRECTIONS.join(', ')}" if layout.key?('direction') && !DIRECTIONS.include?(layout['direction'])
    errs << "diagram.layout.max_zoom must be a number in #{MAX_ZOOM.min}..#{MAX_ZOOM.max}" if layout.key?('max_zoom') && !range?(layout['max_zoom'], MAX_ZOOM)
    errs
  end

  # Nodes and edges share one id space: steps name either by id.
  def id_errors(items)
    errs = items.map { |i| i['id'] }.reject { |id| id.to_s.match?(ID_RE) }.map { |id| "diagram id #{id.inspect} must match [a-z0-9][a-z0-9-]*" }
    items.map { |i| i['id'] }.tally.each { |id, n| errs << "diagram id #{id.inspect} is not unique across nodes and edges" if n > 1 }
    errs
  end

  def lanes_errors(spec, lanes)
    errs = []
    errs << "diagram has #{lanes.size} lanes; the cap is #{MAX_LANES}" if lanes.size > MAX_LANES
    if spec.key?('lane_direction')
      errs << "diagram.lane_direction must be one of #{LANE_DIRECTIONS.join(', ')}" unless LANE_DIRECTIONS.include?(spec['lane_direction'])
      errs << 'diagram.lane_direction needs lanes' if lanes.empty?
    end
    lanes.each do |lane|
      label = "diagram lane #{lane['id'].inspect}"
      errs << "#{label}: unknown keys: #{(lane.keys - LANE_FIELDS).join(', ')}" unless (lane.keys - LANE_FIELDS).empty?
      errs << "#{label}: label must be a non-empty string" unless lane['label'].is_a?(String) && !lane['label'].strip.empty?
      errs.concat(color_value_errors(lane, label))
      errs.concat(icon_errors(lane, label))
    end
    errs
  end

  def node_errors(node, lane_ids = [])
    label = "diagram node #{node['id'].inspect}"
    errs = []
    errs << "#{label}: lane #{node['lane'].inspect} is not a lane" if node.key?('lane') && !lane_ids.include?(node['lane'])
    errs << "#{label}: label must be a non-empty string" unless node['label'].is_a?(String) && !node['label'].strip.empty?
    errs << "#{label}: role must be one of #{NODE_ROLES.join(', ')}" if node.key?('role') && !NODE_ROLES.include?(node['role'])
    errs << "#{label}: position must be { x, y } numbers" if node.key?('position') && !point?(node['position'])
    errs.concat(color_value_errors(node, label))
    errs.concat(icon_errors(node, label))
  end

  def icon_errors(node, label)
    errs = []
    if node.key?('icon') && !icon_names.include?(node['icon'])
      errs << "#{label}: icon #{node['icon'].inspect} is not a vendored icon; available: #{icon_names.join(', ')}"
    end
    errs << "#{label}: icon_weight needs an icon" if node.key?('icon_weight') && !node.key?('icon')
    if node.key?('icon_weight') && !ICON_WEIGHTS.include?(node['icon_weight'])
      errs << "#{label}: icon_weight must be one of #{ICON_WEIGHTS.join(', ')}"
    end
    errs
  end

  def edge_errors(edge, node_ids)
    label = "diagram edge #{edge['id'].inspect}"
    errs = %w[source target].filter_map { |k| "#{label}: #{k} #{edge[k].inspect} is not a node" unless node_ids.include?(edge[k]) }
    errs << "#{label}: label must be a string" if edge.key?('label') && !edge['label'].is_a?(String)
    errs.concat(color_value_errors(edge, label))
  end

  # `color` is a COLOR_ROLES name or a CSS colour CSS_COLOR accepts.
  def color_value_errors(item, label = nil)
    return [] unless item.key?('color')
    return [] if color?(item['color'])

    [ [ label, "color must be a role (#{COLOR_ROLES.join(', ')}) or a CSS colour (#rgb, #rrggbb, rgb(r, g, b)), not #{item['color'].inspect}" ].compact.join(': ') ]
  end

  def color?(value)
    return false unless value.is_a?(String)
    return true if COLOR_ROLES.include?(value)
    return false unless value.match?(CSS_COLOR)

    value.start_with?('#') || value.scan(/\d+/).all? { |n| n.to_i <= 255 }
  end

  def point?(value) = value.is_a?(Hash) && value.keys.sort == %w[x y] && value.values.all?(Numeric)

  def steps_errors(steps, ids, duration_ms)
    return [ 'diagram.steps must be a list of objects' ] unless steps.is_a?(Array) && steps.all?(Hash)

    last = -1
    steps.each_with_index.flat_map do |step, i|
      errs = []
      t = step['t_ms']
      if !t.is_a?(Integer) || t.negative?
        errs << 't_ms must be a non-negative integer'
      elsif t < last
        errs << 't_ms must be non-decreasing'
      elsif t >= duration_ms
        errs << "t_ms #{t} must be below the scene duration (#{duration_ms} ms)"
      else
        last = t
      end
      errs.concat(op_errors(step, ids))
      errs.map { |e| "diagram step #{i}: #{e}" }
    end
  end

  def op_errors(step, ids)
    op = step['op']
    return [ "op #{op.inspect} must be one of #{DIAGRAM_OPS.join(', ')}" ] unless DIAGRAM_OPS.include?(op)

    errs = []
    errs << 'duration must be a non-negative integer' if step.key?('duration') && !(step['duration'].is_a?(Integer) && !step['duration'].negative?)
    errs.concat(flow_errors(step)) if op == 'flow'
    errs << 'color is only for flow steps' if step.key?('color') && op != 'flow'
    return errs.concat(id_op_errors(step, ids, ID_OPS[op])) if ID_OPS.key?(op)

    case op
    when 'travel'
      errs.concat(ref_errors([ step['lane'] ], ids, %i[lane]))
      errs.concat(ref_errors([ step['id'] ], ids, %i[node])) if step.key?('id')
      errs << 'travel takes one id, not ids' if step.key?('ids')
      errs << 'duration must be positive for travel' if step['duration'] == 0
    when 'move'
      errs.concat(ref_errors([ step['id'] ], ids, %i[node]))
      errs << 'move needs a position of { x, y } numbers' unless point?(step['position'])
    when 'label'
      errs.concat(ref_errors([ step['id'] ], ids, %i[node]))
      errs << 'label needs a text string' unless step['text'].is_a?(String)
    when 'fit_view'
      errs.concat(ref_errors(step['ids'], ids, %i[node])) if step.key?('ids')
      errs << "padding must be a number in #{PADDING.min}..#{PADDING.max}" if step.key?('padding') && !range?(step['padding'], PADDING)
    when 'zoom_to'
      errs << "zoom must be a number in #{ZOOM.min}..#{ZOOM.max}" unless range?(step['zoom'], ZOOM)
    when 'focus'
      errs.concat(ref_errors([ step['id'] ], ids, %i[node]))
      errs << "zoom must be a number in #{ZOOM.min}..#{ZOOM.max}" if step.key?('zoom') && !range?(step['zoom'], ZOOM)
    end
    errs
  end

  def flow_errors(step)
    errs = []
    errs << "count must be an integer in #{FLOW_COUNT.min}..#{FLOW_COUNT.max}" if step.key?('count') && !(step['count'].is_a?(Integer) && FLOW_COUNT.cover?(step['count']))
    errs << 'stagger must be a non-negative integer' if step.key?('stagger') && !(step['stagger'].is_a?(Integer) && !step['stagger'].negative?)
    errs << 'repeat must be a positive integer' if step.key?('repeat') && !(step['repeat'].is_a?(Integer) && step['repeat'].positive?)
    errs << 'loop must be true or false' if step.key?('loop') && ![ true, false ].include?(step['loop'])
    errs << 'flow takes loop or repeat, not both' if step['loop'] == true && step.key?('repeat')
    errs << 'duration must be positive for flow' if step['duration'] == 0
    errs.concat(color_value_errors(step))
  end

  def range?(value, range) = value.is_a?(Numeric) && range.cover?(value)

  def id_op_errors(step, ids, kinds)
    return [ "#{step['op']} takes id or ids, not both" ] if step.key?('id') && step.key?('ids')

    refs = step.key?('ids') ? step['ids'] : [ step['id'] ]
    return [ "#{step['op']} needs id or a non-empty ids list" ] unless refs.is_a?(Array) && !refs.empty? && !refs.include?(nil)

    ref_errors(refs, ids, kinds)
  end

  def ref_errors(refs, ids, kinds)
    return [ 'ids must be a list of ids' ] unless refs.is_a?(Array)

    allowed = kinds.flat_map { |k| ids[k] }
    bad = refs.reject { |r| allowed.include?(r) }
    bad.empty? ? [] : [ "#{bad.map(&:inspect).join(', ')} is not a #{kinds.join(' or ')} id" ]
  end

  # A committed screen that differs from what the generator writes now.
  def drift_errors(scene, root, board = {})
    rel = scene.dig('screen', 'html')
    path = File.join(root, rel)
    return [ "#{rel} does not exist; run walkthrough_diagram.rb on the storyboard" ] unless File.file?(path)
    return [] if File.read(path) == screen(scene, root: root, board: board)

    [ "#{rel} drifted from the storyboard's diagram block; run walkthrough_diagram.rb on the storyboard (or validate --fix)" ]
  end

  # -- rendering ---------------------------------------------------------------

  # Script text inlined inside <script>; data-cf-inline tells inline_screen
  # the body is opaque code, not markup to rewrite.
  def script(body) = %(<script data-cf-inline>#{body.gsub('</script', '<\/script')}</script>)

  # Validation lets nodes, edges, and steps be omitted, but the runtime maps
  # over each, so they are written as empty lists. `<` and `>` become JSON
  # escapes so a label like "<iframe>" reaches the runtime as text instead of
  # markup inline_screen would reject or a tag that could close the script.
  def spec_json(spec)
    keep = spec.is_a?(Hash) ? spec.slice(*SPEC_FIELDS) : {}
    %w[nodes edges steps].each { |key| keep[key] ||= [] }
    JSON.pretty_generate(keep).gsub(/[<>]/) { |c| format('\\u%04x', c.ord) }
  end

  # -- palette -------------------------------------------------------------

  def theme(spec) = spec.is_a?(Hash) && spec['theme'] == 'dark' ? :dark : :light

  # The walkthrough's own tokens: the screens/tokens.css its screens link,
  # so a diagram matches them even inside a repo whose configured tokens
  # path names another stylesheet; else the tokens.css found the way its
  # tokens_css_sha256 is.
  OWN_TOKENS = File.join('screens', 'tokens.css')

  def tokens_path(root)
    return nil unless root

    own = File.join(root, OWN_TOKENS)
    return own if File.file?(own)

    require_relative 'walkthrough_storyboard'
    WalkthroughStoryboard.canonical_tokens(root)
  end

  # The --cf-* colours for a walkthrough at root: its tokens' roles in the
  # theme, else the theme's placeholder.
  def palette(root, theme = :light)
    fallback = theme == :dark ? PALETTE_DARK : PALETTE
    path = tokens_path(root)
    return fallback unless path

    roles = DiagramPalette.resolve(path).public_send(theme)
    PALETTE_ROLES.transform_values { |role| roles.fetch(role) }
  rescue DiagramPalette::Error
    fallback # palette_errors reports it; the screen still renders
  end

  # Each COLOR_ROLES name to its hex in the theme: the token file's first
  # matching variable (through var() and color-mix), else ITEM_DEFAULTS.
  def item_roles(root, theme = :light)
    colors = palette(root, theme)
    vars = token_vars(root, theme)
    found = ITEM_ROLE_SOURCES.to_h do |role, names|
      hit = names.lazy.filter_map { |n| vars[n] && DiagramPalette.color(vars, vars[n]) }.first
      [ role, hit ? DiagramPalette.hex(hit).downcase : ITEM_DEFAULTS.fetch(theme).fetch(role) ]
    end
    { 'accent' => colors['accent'] }.merge(found)
  end

  def token_vars(root, theme)
    path = tokens_path(root)
    return {} unless path

    css = DiagramPalette.strip_comments(File.read(path))
    light = DiagramPalette.declarations(DiagramPalette.root_block(css))
    theme == :dark ? light.merge(DiagramPalette.declarations(DiagramPalette.dark_block(css))) : light
  end

  # One `color` value to { color, tint, ring } hexes over the theme's surface.
  def item_color(value, roles, surface, theme)
    hex = roles[value] || css_hex(value)
    rgb = DiagramPalette.rgb(hex)
    bg = DiagramPalette.rgb(surface)
    mix = ->(share) { DiagramPalette.hex(DiagramPalette.mix(rgb, bg, share)).downcase }
    { 'color' => hex.downcase, 'tint' => mix.(DiagramPalette::TINT_SHARE.fetch(theme)), 'ring' => mix.(RING_SHARE) }
  end

  def css_hex(value)
    return "##{value[1..].chars.map { |c| c * 2 }.join}" if value.size == 4
    return value if value.start_with?('#')

    format('#%02x%02x%02x', *value.scan(/\d+/).map(&:to_i))
  end

  # The resolved colours the runtime draws, keyed by node id, edge id, and
  # flow step index; nil when nothing in the spec carries a colour, so such
  # a screen is written exactly as before colours existed.
  def item_colors(spec, root)
    nodes = Array(spec['nodes']).select { |n| color?(n['color']) }
    edges = Array(spec['edges']).select { |e| color?(e['color']) }
    steps = Array(spec['steps']).each_with_index.select { |s, _| s['op'] == 'flow' && color?(s['color']) }
    return nil if nodes.empty? && edges.empty? && steps.empty?

    th = theme(spec)
    roles = item_roles(root, th)
    surface = palette(root, th)['surface']
    at = ->(v) { item_color(v, roles, surface, th) }
    { 'nodes' => nodes.to_h { |n| [ n['id'], at.(n['color']) ] }, 'edges' => edges.to_h { |e| [ e['id'], at.(e['color']) ] },
      'steps' => steps.to_h { |s, i| [ i.to_s, at.(s['color']) ] } }
  end

  # Readability of every coloured item in the scene's theme: a node's label
  # (the theme's text colour) on its tinted fill clears the WCAG AA text
  # floor, and an edge or dot colour clears the stroke floor on the surface.
  def item_color_errors(spec, root)
    colors = item_colors(spec, root)
    return [] unless colors

    th = theme(spec)
    pal = palette(root, th)
    errs = colors['nodes'].filter_map do |id, c|
      ratio = DiagramPalette.contrast(pal['text'], c['tint'])
      "diagram node #{id.inspect}: label text #{pal['text']} on its #{th} fill #{c['tint']} is #{ratio.round(2)}:1, under #{DiagramPalette::TEXT_MIN}" if ratio < DiagramPalette::TEXT_MIN
    end
    errs += colors['nodes'].filter_map do |id, c|
      next unless Array(spec['nodes']).find { |n| n['id'] == id }&.key?('icon')

      ratio = DiagramPalette.contrast(c['color'], c['tint'])
      "diagram node #{id.inspect}: icon #{c['color']} on its #{th} fill #{c['tint']} is #{ratio.round(2)}:1, under #{DiagramPalette::STROKE_MIN}" if ratio < DiagramPalette::STROKE_MIN
    end
    strokes = colors['nodes'].map { |id, c| [ "node #{id.inspect}", c ] } + colors['edges'].map { |id, c| [ "edge #{id.inspect}", c ] } +
              colors['steps'].map { |i, c| [ "step #{i}", c ] }
    errs + strokes.filter_map do |what, c|
      ratio = DiagramPalette.contrast(c['color'], pal['surface'])
      "diagram #{what}: color #{c['color']} on the #{th} surface #{pal['surface']} is #{ratio.round(2)}:1, under #{DiagramPalette::STROKE_MIN}" if ratio < DiagramPalette::STROKE_MIN
    end
  end

  # The light theme's contrast floors (DiagramPalette's own checks plus the
  # node fills); an unreadable token file is an error, not a silent default.
  def palette_errors(root, theme = :light)
    path = tokens_path(root)
    return [] unless path

    result = DiagramPalette.resolve(path)
    roles = result.public_send(theme)
    node = NODE_CONTRAST.filter_map do |fg, bg|
      ratio = DiagramPalette.contrast(roles[fg], roles[bg])
      "#{theme}: #{fg} on #{bg} is #{ratio.round(2)}:1, under #{DiagramPalette::TEXT_MIN}" if ratio < DiagramPalette::TEXT_MIN
    end
    (result.warnings.grep(/\A#{theme}:/) + node).map { |w| "diagram palette from #{path}: #{w}" }
  rescue DiagramPalette::Error => e
    [ "diagram palette from #{path}: #{e.message}" ]
  end

  # Each lane's colour and band tints in the scene's theme: { id, label,
  # color, tint, tint_hl }, in spec order. A lane with no colour takes the
  # series role of its position, so neighbouring lanes read apart.
  def lane_colors(spec, root)
    lanes = spec.is_a?(Hash) && spec['lanes'].is_a?(Array) ? spec['lanes'].grep(Hash) : []
    return [] if lanes.empty?

    th = theme(spec)
    roles = item_roles(root, th)
    bg = DiagramPalette.rgb(palette(root, th)['surface'])
    lanes.each_with_index.map do |lane, i|
      value = color?(lane['color']) ? lane['color'] : "series-#{(i % SERIES) + 1}"
      hex = (roles[value] || css_hex(value)).downcase
      mix = ->(share) { DiagramPalette.hex(DiagramPalette.mix(DiagramPalette.rgb(hex), bg, share)).downcase }
      icon = icon_names.include?(lane['icon']) ? "#{lane['icon']}/#{ICON_WEIGHTS.include?(lane['icon_weight']) ? lane['icon_weight'] : 'regular'}" : nil
      { 'id' => lane['id'], 'label' => lane['label'], 'color' => hex, 'tint' => mix.(LANE_TINT_SHARE.fetch(th)), 'tint_hl' => mix.(LANE_HL_SHARE) }
        .merge(icon ? { 'icon' => icon } : {})
    end
  end

  # A lane label (the theme's text colour) clears the WCAG AA text floor on
  # its band at rest and highlighted, the lane colour (its label bar and
  # travel marker) clears the stroke floor on the surface, and a lane icon
  # (drawn in that colour) clears it on the band.
  def lane_color_errors(spec, root)
    th = theme(spec)
    pal = palette(root, th)
    lane_colors(spec, root).flat_map do |c|
      errs = %w[tint tint_hl].filter_map do |key|
        ratio = DiagramPalette.contrast(pal['text'], c[key])
        "diagram lane #{c['id'].inspect}: label text #{pal['text']} on its #{th} band #{c[key]} is #{ratio.round(2)}:1, under #{DiagramPalette::TEXT_MIN}" if ratio < DiagramPalette::TEXT_MIN
      end
      if c['icon']
        errs.concat(%w[tint tint_hl].filter_map do |key|
          ratio = DiagramPalette.contrast(c['color'], c[key])
          "diagram lane #{c['id'].inspect}: icon #{c['color']} on its #{th} band #{c[key]} is #{ratio.round(2)}:1, under #{DiagramPalette::STROKE_MIN}" if ratio < DiagramPalette::STROKE_MIN
        end)
      end
      ratio = DiagramPalette.contrast(c['color'], pal['surface'])
      errs << "diagram lane #{c['id'].inspect}: color #{c['color']} on the #{th} surface #{pal['surface']} is #{ratio.round(2)}:1, under #{DiagramPalette::STROKE_MIN}" if ratio < DiagramPalette::STROKE_MIN
      errs
    end
  end

  # The lane data and layer script, inlined between the bundle and the
  # runtime (it lays the lanes out before the runtime reads the spec), and
  # the call that attaches its drawing after the runtime. Both are empty for
  # a spec without lanes, so such a screen keeps its bytes.
  def lanes_scripts(spec, root)
    lanes = lane_colors(spec, root)
    return [ '', '' ] if lanes.empty?

    data = { 'direction' => spec['lane_direction'] || 'horizontal', 'lanes' => lanes }
    json = JSON.generate(data).gsub(/[<>]/) { |c| format('\\u%04x', c.ord) }
    [ %(<script type="application/json" id="cf-diagram-lanes">#{json}</script>\n#{script(File.read(LANES_RUNTIME))}\n),
      %(\n#{script('window.__cfLanes && window.__cfLanes.attach();')}) ]
  end

  def palette_css(colors) = ":root { #{colors.map { |k, v| "--cf-#{k}: #{v};" }.join(' ')} }"

  # The item colours as JSON for the runtime, or nothing at all when the
  # spec has none, so an uncoloured screen keeps its bytes.
  def colors_script(spec, root)
    colors = spec.is_a?(Hash) && item_colors(spec, root)
    colors ? %(<script type="application/json" id="cf-diagram-colors">#{JSON.generate(colors)}</script>\n) : ''
  end

  # The path data of each icon the spec's nodes and lanes use, keyed
  # name/weight, or nothing at all when none has one, so an iconless screen
  # keeps its bytes.
  def icons_script(spec)
    items = spec.is_a?(Hash) ? Array(spec['nodes']) + Array(spec['lanes']) : []
    used = items.select { |n| n.is_a?(Hash) && icon_names.include?(n['icon']) }
    return '' if used.empty?

    paths = used.to_h do |n|
      weight = ICON_WEIGHTS.include?(n['icon_weight']) ? n['icon_weight'] : 'regular'
      [ "#{n['icon']}/#{weight}", icon_set.dig('icons', n['icon'], weight) ]
    end
    %(<script type="application/json" id="cf-diagram-icons">#{JSON.generate(paths.sort.to_h)}</script>\n)
  end

  # Where the scene sits in the frame: the bottom inset keeps the camera's
  # fit and focus targets above the caption band players draw cues in.
  def frame(board)
    viewport = PrototypeCapture::DEFAULT_VIEWPORT.merge((board || {})['viewport'] || {})
    { 'bottom_inset' => (viewport['h'] * PrototypeUxLint::CAPTION_BAND).ceil }
  end

  # The full, self-contained screen file for a diagram scene. root locates
  # the tokens.css; board gives the viewport the caption inset comes from.
  def screen(scene, root: nil, board: {})
    lanes_pre, lanes_post = lanes_scripts(scene['diagram'], root)
    title = (scene['title'] || 'Diagram').to_s.gsub(/[<>&"]/, '<' => '&lt;', '>' => '&gt;', '&' => '&amp;', '"' => '&quot;')
    <<~HTML
      #{GENERATED}
      <!-- xyflow #{XYFLOW_VERSION} sha256 #{XYFLOW_SHA256} -->
      <!doctype html>
      <html lang="en">
      <head>
      <meta charset="utf-8">
      <title>#{title}</title>
      <style>#{palette_css(palette(root, theme(scene['diagram'])))}</style>
      </head>
      <body>
      <main id="cf-diagram-root" aria-label="#{title}"></main>
      <script type="application/json" id="cf-diagram">
      #{spec_json(scene['diagram'])}
      </script>
      <script type="application/json" id="cf-diagram-frame">#{JSON.generate(frame(board))}</script>
      #{colors_script(scene['diagram'], root)}#{icons_script(scene['diagram'])}#{script(File.read(XYFLOW_BUNDLE))}
      #{lanes_pre}#{script(File.read(RUNTIME))}#{lanes_post}
      </body>
      </html>
    HTML
  end

  # Writes each diagram scene's screen (or only `only`); returns the paths.
  def write_screens(board, root, only: nil)
    Array(board['scenes']).select { |s| diagram?(s) && s.dig('screen', 'html') && (only.nil? || s['id'] == only) }.map do |scene|
      out = scene.dig('screen', 'html')
      FileUtils.mkdir_p(File.dirname(File.join(root, out)))
      File.write(File.join(root, out), screen(scene, root: root, board: board))
      out
    end
  end

  # storyboard.md lines: the node and edge lists and a step table.
  def md(scene)
    spec = scene['diagram'] || {}
    out = Array(spec['lanes']).map { |l| "- Lane `#{l['id']}`: #{l['label']}#{l['icon'] ? " [#{l['icon']}]" : ''}" }
    out.concat(Array(spec['nodes']).map { |n| "- Node `#{n['id']}`: #{n['label']}#{n['icon'] ? " [#{n['icon']}]" : ''}#{n['position'] ? ' (pinned)' : ''}#{n['lane'] ? " (lane #{n['lane']})" : ''}" })
    out.concat(Array(spec['edges']).map { |e| "- Edge `#{e['id']}`: #{e['source']} -> #{e['target']}#{e['label'] ? " (#{e['label']})" : ''}" })
    out << "- Initial: #{Array(spec['initial']).join(', ')}" unless Array(spec['initial']).empty?
    steps = Array(spec['steps'])
    return out if steps.empty?

    out << '' << '| t_ms | op | target |' << '| --- | --- | --- |'
    steps.each { |s| out << "| #{s['t_ms']} | #{s['op']} | #{(Array(s['ids'] || s['id']) + Array(s['lane'])).join(', ')} |" }
    out
  end
end

