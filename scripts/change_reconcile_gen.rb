#!/usr/bin/env ruby
# frozen_string_literal: true

require 'digest'
require 'fileutils'
require 'json'
require 'optparse'
require_relative 'change_prod_envelope'
require_relative 'change_prod_runner_gen'

# Generates .github/workflows/cf-prod-reconcile.yml: the backstop for a
# maintenance lease that outlived its window. Every ten minutes it reads the
# journal refs, and for a lease that expired with no mutation started (or an
# op observed complete) it runs maintenance verify and exit. For a journal at
# `launching` or `uncertain` it pages (the job fails) and leaves maintenance on.
#
# Its role is its own: runners.prod.reconcile_role, never the op role. The
# trust is the repo, the default branch and this workflow, with no Environment,
# so approving production never lets this job run an op.
module ChangeReconcileGen
  class Refused < StandardError; end

  WORKFLOW = '.github/workflows/cf-prod-reconcile.yml'
  HEADER = '# GENERATED by change_reconcile_gen.rb. Do not edit: doctor flags a changed file.'
  CRON = '*/10 * * * *'
  ROLE = ChangeProdRunnerGen::ROLE
  REGION = ChangeProdRunnerGen::REGION
  SCRIPT = "#{ChangeProdRunnerGen::SCRIPTS}/change_maintenance.rb".freeze

  module_function

  # The workflow text; raises Refused when the config cannot reconcile.
  def generate(config)
    role = role_of(config)
    region = config.dig('change_config', 'runners', 'prod', 'region') || 'us-east-1'
    raise Refused, 'runner region is malformed' unless region.to_s.match?(REGION)

    body = [ preamble, 'jobs:', job(role, region) ].join("\n")
    "#{HEADER}\n# digest: sha256:#{Digest::SHA256.hexdigest(body)}\n#{body}"
  end

  # True when the config has a maintenance enter command, so a lease can exist.
  def needed?(config)
    config.dig('change_config', 'maintenance', 'enter').is_a?(Hash)
  end

  def role_of(config)
    role = config.dig('change_config', 'runners', 'prod', 'reconcile_role')
    raise Refused, 'runners.prod.reconcile_role is missing or not an IAM role ARN' unless role.to_s.match?(ROLE)

    role
  end

  def preamble
    <<~YAML
      name: cf-prod-reconcile
      on:
        schedule:
          - cron: "#{CRON}"
        workflow_dispatch:
      permissions:
        contents: read
      concurrency:
        group: cf-prod-reconcile
        cancel-in-progress: false
    YAML
  end

  # contents: write is for the journal refs only; the role itself reads the
  # journal, runs maintenance verify and exit, and nothing else.
  def job(role, region)
    <<~YAML.gsub(/^(?=.)/, '  ')
      reconcile:
        if: github.ref == format('refs/heads/{0}', github.event.repository.default_branch)
        runs-on: ubuntu-24.04
        permissions:
          id-token: write
          contents: write
        steps:
          - uses: actions/checkout@v5
            with:
              ref: ${{ github.event.repository.default_branch }}
              fetch-depth: 0
              path: base
          - uses: ruby/setup-ruby@v1
            with:
              ruby-version: "3.4"
          - uses: aws-actions/configure-aws-credentials@v4
            with:
              role-to-assume: "#{role}"
              aws-region: #{region}
          - name: exit expired leases that are safe, page on the rest
            run: ruby base/#{SCRIPT} reconcile --config base/CHANGE.md --repo base
    YAML
  end

  def tampered?(text)
    header, digest, body = text.split("\n", 3)
    match = digest.to_s.match(/\A# digest: sha256:([0-9a-f]{64})\z/)
    return true unless header == HEADER && match && body

    Digest::SHA256.hexdigest(body) != match[1]
  end

  def drifted?(text, config) = generate(config) != text

  # The trust condition the reconcile role needs: the repo, the default branch
  # and this workflow, nothing else.
  def trust_policy(config, sub_prefix: nil, default_branch: 'main')
    prefix = sub_prefix || '<sub_claim_prefix>'
    pinned = "#{ChangeProdRunnerGen.workflow_owner_repo(sub_prefix)}/#{WORKFLOW}@refs/heads/#{default_branch}"
    sub = "#{prefix}:ref:refs/heads/#{default_branch}:job_workflow_ref:#{pinned}"
    condition = { 'StringEquals' => { 'token.actions.githubusercontent.com:aud' => 'sts.amazonaws.com', 'token.actions.githubusercontent.com:sub' => sub } }
    [ "trust condition for #{role_of(config)} (reconcile): #{JSON.generate('Condition' => condition)}" ]
  end

  def run(argv, stdout: $stdout, stderr: $stderr)
    opts = { root: '.' }
    OptionParser.new do |o|
      o.on('--config PATH') { |v| opts[:config] = v }
      o.on('--root PATH') { |v| opts[:root] = v }
      o.on('--sub-prefix PREFIX', ChangeProdRunnerGen::SUB_PREFIX) { |v| opts[:sub_prefix] = v }
      o.on('--default-branch BRANCH', %r{\A[A-Za-z0-9._/-]+\z}) { |v| opts[:default_branch] = v }
      o.on('--check') { opts[:check] = true }
    end.parse!(argv)
    config = ChangeProdEnvelope.load_config(opts.fetch(:config))
    return check(opts, config, stdout, stderr) if opts[:check]

    path = File.join(opts[:root], WORKFLOW)
    FileUtils.mkdir_p(File.dirname(path))
    File.write(path, generate(config))
    stdout.puts "wrote #{path}"
    ChangeProdRunnerGen.vendor(opts[:root]).each { |file| stdout.puts "wrote #{file}" }
    trust_policy(config, **opts.slice(:sub_prefix, :default_branch)).each { |line| stdout.puts line }
    0
  rescue Refused, ChangeProdEnvelope::Invalid, OptionParser::ParseError, KeyError => e
    stderr.puts "[cf-reconcile] refused: #{e.message}"
    1
  end

  def check(opts, config, stdout, stderr)
    path = File.join(opts[:root], WORKFLOW)
    unless File.exist?(path) && !tampered?(File.read(path))
      stderr.puts "[cf-reconcile] #{WORKFLOW} is missing or was edited by hand; regenerate it"
      return 1
    end
    if drifted?(File.read(path), config)
      stderr.puts "[cf-reconcile] #{WORKFLOW} drifted from the base config; regenerate"
      return 1
    end
    stdout.puts "#{WORKFLOW} is unchanged since generation"
    0
  end
end

exit(ChangeReconcileGen.run(ARGV)) if __FILE__ == $PROGRAM_NAME
