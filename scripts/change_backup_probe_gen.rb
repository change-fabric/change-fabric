#!/usr/bin/env ruby
# frozen_string_literal: true

require 'digest'
require 'fileutils'
require 'json'
require 'optparse'
require_relative 'change_prod_envelope'
require_relative 'change_prod_runner_gen'

# Generates .github/workflows/cf-restore-probe.yml: the weekly restore probe for
# every backup that declares restore_probe.oidc_roles. One job per backup and
# profile, each assuming that profile's role (read-only IAM for the restore and
# its teardown), running `change_backup.rb probe` from the default branch and
# uploading the evidence record as an artifact, success or failure, so the
# runner can tell a failed probe from a missing one.
#
# The schedule is its own generated workflow, not a change_schedule_config entry:
# schedules run lanes, and a probe is not a lane. Probes run weekly only, since
# a restore costs real money.
module ChangeBackupProbeGen
  class Refused < StandardError; end

  WORKFLOW = '.github/workflows/cf-restore-probe.yml'
  HEADER = '# GENERATED by change_backup_probe_gen.rb. Do not edit: doctor flags a changed file.'
  # Monday 05:17 UTC, off the hour so it does not queue with everyone's jobs.
  CRON = '17 5 * * 1'
  RETENTION_DAYS = 14
  NAME = ChangeProdEnvelope::NAME
  ROLE = ChangeProdRunnerGen::ROLE
  REGION = ChangeProdRunnerGen::REGION
  SCRIPT = "#{ChangeProdRunnerGen::SCRIPTS}/change_backup.rb".freeze

  module_function

  # The workflow text; raises Refused when no backup can be probed.
  def generate(config)
    jobs = probes(config)
    raise Refused, 'no backup declares restore_probe.oidc_roles' if jobs.empty?

    region = region_of(config)
    body = [ preamble, 'jobs:', *jobs.map { |backup, profile, role| job(backup, profile, role, region) } ].join("\n")
    "#{HEADER}\n# digest: sha256:#{Digest::SHA256.hexdigest(body)}\n#{body}"
  end

  # [[backup, profile, role]], sorted, for every probe with oidc_roles.
  def probes(config)
    backups = config.dig('change_config', 'backups')
    return [] unless backups.is_a?(Hash)

    backups.keys.sort.flat_map do |name|
      probe = backups[name].is_a?(Hash) ? backups[name]['restore_probe'] : nil
      roles = probe.is_a?(Hash) ? probe['oidc_roles'] : nil
      next [] unless roles.is_a?(Hash)

      roles.keys.sort.map { |profile| [ checked_name(name), checked_name(profile), checked_role(profile, roles[profile]) ] }
    end
  end

  def region_of(config)
    region = config.dig('change_config', 'runners', 'prod', 'region') || 'us-east-1'
    raise Refused, 'runner region is malformed' unless region.to_s.match?(REGION)

    region
  end

  def checked_name(name)
    raise Refused, "#{name.inspect} is not a plain name" unless name.to_s.match?(NAME)

    name.to_s
  end

  def checked_role(profile, role)
    raise Refused, "probe role for #{profile} is not an IAM role ARN" unless role.to_s.match?(ROLE)

    role
  end

  def preamble
    <<~YAML
      name: cf-restore-probe
      on:
        schedule:
          - cron: "#{CRON}"
        workflow_dispatch:
      permissions:
        contents: read
      concurrency:
        group: cf-restore-probe
        cancel-in-progress: false
    YAML
  end

  def job_id(backup, profile) = "probe-#{backup.tr('_', '-')}-#{profile.tr('_', '-')}"

  def job(backup, profile, role, region)
    <<~YAML.gsub(/^(?=.)/, '  ')
      #{job_id(backup, profile)}:
        if: github.ref == format('refs/heads/{0}', github.event.repository.default_branch)
        runs-on: ubuntu-24.04
        permissions:
          id-token: write
          contents: read
        steps:
          - uses: actions/checkout@v5
            with:
              ref: ${{ github.event.repository.default_branch }}
              path: base
          - uses: ruby/setup-ruby@v1
            with:
              ruby-version: "3.4"
          - uses: aws-actions/configure-aws-credentials@v4
            with:
              role-to-assume: "#{role}"
              aws-region: #{region}
          - name: restore and tear down, then record the result
            run: ruby base/#{SCRIPT} probe --config base/CHANGE.md --repo base --backup #{backup} --environment #{profile} --out evidence
          - uses: actions/upload-artifact@v4
            if: always()
            with:
              name: cf-probe-#{backup}-#{profile}
              path: evidence/
              retention-days: #{RETENTION_DAYS}
              if-no-files-found: error
    YAML
  end

  def tampered?(text)
    header, digest, body = text.split("\n", 3)
    match = digest.to_s.match(/\A# digest: sha256:([0-9a-f]{64})\z/)
    return true unless header == HEADER && match && body

    Digest::SHA256.hexdigest(body) != match[1]
  end

  # True when regenerating from `config` would not reproduce `text`.
  def drifted?(text, config) = generate(config) != text

  # The trust condition each probe role needs: the repo, the default branch and
  # this workflow, nothing else. The sub carries the ref context, not an
  # Environment, because the probe job names none.
  def trust_policy(config, sub_prefix: nil, default_branch: 'main')
    prefix = sub_prefix || '<sub_claim_prefix>'
    pinned = "#{ChangeProdRunnerGen.workflow_owner_repo(sub_prefix)}/#{WORKFLOW}@refs/heads/#{default_branch}"
    sub = "#{prefix}:ref:refs/heads/#{default_branch}:job_workflow_ref:#{pinned}"
    probes(config).map do |backup, profile, role|
      condition = { 'StringEquals' => { 'token.actions.githubusercontent.com:aud' => 'sts.amazonaws.com', 'token.actions.githubusercontent.com:sub' => sub } }
      "trust condition for #{role} (#{backup} #{profile}): #{JSON.generate('Condition' => condition)}"
    end
  end

  def run(argv, stdout: $stdout, stderr: $stderr)
    opts = { root: '.' }
    OptionParser.new do |o|
      o.on('--config PATH') { |v| opts[:config] = v }
      o.on('--root PATH') { |v| opts[:root] = v }
      o.on('--sub-prefix PREFIX', ChangeProdRunnerGen::SUB_PREFIX) { |v| opts[:sub_prefix] = v }
      o.on('--default-branch BRANCH', %r{\A[A-Za-z0-9._/-]+\z}) { |v| opts[:default_branch] = v }
      o.on('--check') { opts[:check] = true }
    end.parse!(argv)
    config = ChangeProdEnvelope.load_config(opts.fetch(:config))
    return check(opts, config, stdout, stderr) if opts[:check]

    path = File.join(opts[:root], WORKFLOW)
    FileUtils.mkdir_p(File.dirname(path))
    File.write(path, generate(config))
    stdout.puts "wrote #{path}"
    ChangeProdRunnerGen.vendor(opts[:root]).each { |file| stdout.puts "wrote #{file}" }
    trust_policy(config, **opts.slice(:sub_prefix, :default_branch)).each { |line| stdout.puts line }
    0
  rescue Refused, ChangeProdEnvelope::Invalid, OptionParser::ParseError, KeyError => e
    stderr.puts "[cf-backup] refused: #{e.message}"
    1
  end

  def check(opts, config, stdout, stderr)
    path = File.join(opts[:root], WORKFLOW)
    unless File.exist?(path) && !tampered?(File.read(path))
      stderr.puts "[cf-backup] #{WORKFLOW} is missing or was edited by hand; regenerate it"
      return 1
    end
    if drifted?(File.read(path), config)
      stderr.puts "[cf-backup] #{WORKFLOW} drifted from the base config; regenerate"
      return 1
    end
    stale = ChangeProdRunnerGen.stale_vendored(opts[:root])
    unless stale.empty?
      stderr.puts "[cf-backup] vendored scripts are missing or differ from this toolkit: #{stale.join(', ')}; regenerate"
      return 1
    end
    stdout.puts "#{WORKFLOW} and its vendored scripts are unchanged since generation"
    0
  end
end

exit(ChangeBackupProbeGen.run(ARGV)) if __FILE__ == $PROGRAM_NAME
