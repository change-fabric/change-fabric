#!/usr/bin/env ruby
# frozen_string_literal: true

require 'digest'
require 'fileutils'
require 'optparse'
require_relative 'change_prod_envelope'

# Generates .github/workflows/cf-prod.yml, the bounded prod runner.
#
# One validate job reads the request and approval refs, rechecks the envelope
# against base-branch config, verifies the approval proof offline against the
# pinned credentials and checks provenance, all without a credential. Then one
# job per allowed environment, each with a literal `environment:` and a literal
# OIDC role, selected by `if:` on the validated envelope's environment. A
# mismatch between profile, environment and role refuses before any credential
# step, because a job that does not match never starts.
#
# The production job is emitted only when `production_blockers` is empty. This
# release has no op executor, so the blocker list is never empty: only staging
# is generated. Config is read from a fixture or CHANGE.md frontmatter passed
# on the command line, not yet from the 0.25.0 keys.
module ChangeProdRunnerGen
  class Refused < StandardError; end

  WORKFLOW = '.github/workflows/cf-prod.yml'
  SCRIPTS = '.github/cf-prod/scripts'
  # The runner's own code, copied into the consumer repo under SCRIPTS with the
  # same relative layout so each require_relative resolves. A workflow that
  # calls a script that is not there would fail before verifying anything.
  VENDORED = %w[
    change_prod_gate.rb change_prod_envelope.rb change_prod_store.rb change_frontmatter.rb
    approval_console/canonical.rb approval_console/cbor.rb approval_console/verifier.rb
  ].freeze
  CREDENTIALS = '.github/cf-prod-approval-credentials.json'
  HEADER = '# GENERATED by change_prod_runner_gen.rb. Do not edit: doctor flags a changed file.'
  ROLE = %r{\Aarn:aws:iam::\d{12}:role/[A-Za-z0-9+=,.@_/-]{1,128}\z}
  REGION = /\A[a-z]{2}(-[a-z]+)+-\d\z/
  NAME = ChangeProdEnvelope::NAME
  # Flipped by the PR that lands the op executor, backups and maintenance
  # windows (plan phases 3 and 4).
  EXECUTOR_LANDED = false
  # While anything blocks production, only these profiles, mapped to the
  # same-named environment, are emitted. An allowlist, not a deny of one name:
  # `prod`, `live` or a staging key mapped to production never gets a job.
  SAFE_PROFILES = %w[staging].freeze

  module_function

  # Why the production job cannot be emitted yet. Empty only when the console's
  # offline verifier and its enroll and request verbs exist and the executor
  # has landed.
  def production_blockers(root: File.expand_path('..', __dir__), executor: EXECUTOR_LANDED)
    reasons = []
    reasons << 'the runner has no op executor, backups or maintenance windows yet (plan phases 3 and 4)' unless executor
    reasons << 'approval console offline verifier is missing' unless File.exist?(File.join(root, 'scripts/approval_console/verifier.rb'))
    cli = File.join(root, 'scripts/approval_console.rb')
    text = File.exist?(cli) ? File.read(cli) : ''
    %w[enroll request].each do |verb|
      reasons << "approval console has no #{verb} verb (console phases 5 and 6)" unless text.include?("when '#{verb}'")
    end
    reasons
  end

  # Returns the workflow text. `config` is the frontmatter hash.
  def generate(config, blockers: production_blockers, repo: nil)
    runner = runner_config(config)
    jobs = environments(runner, blockers)
    raise Refused, 'no environment can be emitted' if jobs.empty?

    body = render(jobs, runner, config, blockers)
    "#{HEADER}\n# digest: sha256:#{Digest::SHA256.hexdigest(body)}\n#{body}"
  end

  # True when the file's digest line no longer matches its body (everything
  # after the two header lines).
  def tampered?(text)
    header, digest, body = text.split("\n", 3)
    match = digest.to_s.match(/\A# digest: sha256:([0-9a-f]{64})\z/)
    return true unless header == HEADER && match && body

    Digest::SHA256.hexdigest(body) != match[1]
  end

  def runner_config(config)
    runner = config.dig('change_config', 'runners', 'prod') if config.is_a?(Hash)
    raise Refused, 'config has no change_config.runners.prod' unless runner.is_a?(Hash)
    raise Refused, "runner kind #{runner['kind'].inspect} is not github_actions" unless runner['kind'] == 'github_actions'
    raise Refused, 'runner workflow must be .github/workflows/cf-prod.yml' unless runner['workflow'] == WORKFLOW

    runner
  end

  # profile => [environment, role], in profile name order. Anything outside the
  # allowed charset refuses, since these values are written into YAML.
  def environments(runner, blockers)
    mapping = runner['environments']
    roles = runner['oidc_roles']
    raise Refused, 'runner needs environments and oidc_roles' unless mapping.is_a?(Hash) && roles.is_a?(Hash)

    triples = mapping.keys.sort.map { |profile| [ profile, checked_environment(profile, mapping[profile]), checked_role(profile, roles[profile]) ] }
    duplicates = triples.map { |_, environment, _| environment }.tally.select { |_, count| count > 1 }.keys
    raise Refused, "profiles share an environment (#{duplicates.join(', ')}); one approval must select one role" unless duplicates.empty?
    return triples if blockers.empty?

    triples.select { |profile, environment, _| SAFE_PROFILES.include?(profile) && environment == profile }
  end

  def checked_environment(profile, name)
    raise Refused, "environment for #{profile} is not a plain name" unless profile.to_s.match?(NAME) && name.to_s.match?(NAME)

    name
  end

  def checked_role(profile, role)
    raise Refused, "oidc role for #{profile} is missing or not an IAM role ARN" unless role.to_s.match?(ROLE)

    role
  end

  def render(jobs, runner, _config, blockers)
    allowed = jobs.map { |_, environment, _| environment }.join(',')
    region = runner['region'] || 'us-east-1'
    raise Refused, 'runner region is malformed' unless region.to_s.match?(REGION)

    notes = blockers.empty? ? '' : "# production is not emitted: #{blockers.join('; ')}\n"
    [ notes + preamble, validate_job(allowed), claim_job(allowed), *jobs.map { |profile, env, role| environment_job(profile, env, role, region) } ].join("\n")
  end

  def preamble
    <<~YAML
      name: cf-prod
      on:
        workflow_dispatch:
          inputs:
            request_id:
              description: cf.prod.request/1 request id (uuid)
              required: true
              type: string
      permissions:
        contents: read
      concurrency:
        group: cf-prod
        cancel-in-progress: false
    YAML
  end

  def gate(verb, allowed)
    "ruby base/#{SCRIPTS}/change_prod_gate.rb #{verb} --request-id \"$REQUEST_ID\" --repo base " \
      "--config base/CHANGE.md --credentials base/#{CREDENTIALS} --allow-environments #{allowed} " \
      '--default-branch "$DEFAULT_BRANCH"'
  end

  def validate_job(allowed)
    <<~YAML
      jobs:
        validate:
          if: github.ref == format('refs/heads/{0}', github.event.repository.default_branch)
          runs-on: ubuntu-24.04
          permissions:
            contents: read
          outputs:
            environment: ${{ steps.verify.outputs.environment }}
            version: ${{ steps.verify.outputs.version }}
          steps:
            - uses: actions/checkout@v5
              with:
                ref: ${{ github.event.repository.default_branch }}
                fetch-depth: 0
                path: base
            - uses: ruby/setup-ruby@v1
              with:
                ruby-version: "3.4"
            - name: verify request, approval and config
              id: verify
              env:
                REQUEST_ID: ${{ inputs.request_id }}
                DEFAULT_BRANCH: ${{ github.event.repository.default_branch }}
              run: #{gate('verify', allowed)}
    YAML
  end

  # A separate job so the one that holds the OIDC token never needs contents:
  # write: creating the claim ref is the only write, and it precedes every
  # credential step because the environment jobs need it.
  def claim_job(allowed)
    <<~YAML.gsub(/^(?=.)/, '  ')
      claim:
        needs: validate
        if: needs.validate.outputs.environment != ''
        runs-on: ubuntu-24.04
        permissions:
          contents: write
        steps:
          - uses: actions/checkout@v5
            with:
              ref: ${{ github.event.repository.default_branch }}
              fetch-depth: 0
              path: base
          - uses: actions/checkout@v5
            with:
              ref: ${{ needs.validate.outputs.version }}
              fetch-depth: 0
              path: version
          - uses: ruby/setup-ruby@v1
            with:
              ruby-version: "3.4"
          - name: reverify, check provenance and claim
            env:
              REQUEST_ID: ${{ inputs.request_id }}
              DEFAULT_BRANCH: ${{ github.event.repository.default_branch }}
            run: #{gate('claim', allowed).sub('--default-branch', '--version-root version --default-branch')}
    YAML
  end

  def environment_job(profile, environment, role, region)
    <<~YAML.gsub(/^(?=.)/, '  ')
      #{job_id(profile)}:
        needs: [validate, claim]
        if: needs.validate.outputs.environment == '#{environment}'
        runs-on: ubuntu-24.04
        environment: #{environment}
        permissions:
          id-token: write
          contents: read
        steps:
          - uses: actions/checkout@v5
            with:
              ref: ${{ github.event.repository.default_branch }}
              fetch-depth: 0
              path: base
          - uses: actions/checkout@v5
            with:
              ref: ${{ needs.validate.outputs.version }}
              fetch-depth: 0
              path: version
          - uses: ruby/setup-ruby@v1
            with:
              ruby-version: "3.4"
          - name: recheck the approval has not expired before any credential
            env:
              REQUEST_ID: ${{ inputs.request_id }}
              DEFAULT_BRANCH: ${{ github.event.repository.default_branch }}
            run: #{gate('recheck', environment).sub('--default-branch', '--version-root version --default-branch')}
          - uses: aws-actions/configure-aws-credentials@v4
            with:
              role-to-assume: "#{role}"
              aws-region: #{region}
          - name: run the declared op
            run: ruby base/#{SCRIPTS}/change_prod_gate.rb run
    YAML
  end

  def job_id(profile) = "run-#{profile.tr('_', '-')}"

  def oidc_command(repo)
    "gh api -X PUT repos/#{repo || '<o>/<r>'}/actions/oidc/customization/sub -F use_default=false " \
      "-f 'include_claim_keys[]=repo' -f 'include_claim_keys[]=context' -f 'include_claim_keys[]=workflow_ref'"
  end

  def run(argv, stdout: $stdout, stderr: $stderr)
    opts = { root: '.' }
    OptionParser.new do |o|
      o.on('--config PATH') { |v| opts[:config] = v }
      o.on('--root PATH') { |v| opts[:root] = v }
      o.on('--repo OWNER/NAME') { |v| opts[:repo] = v }
      o.on('--check') { opts[:check] = true }
    end.parse!(argv)
    return check(opts, stdout, stderr) if opts[:check]

    text = generate(ChangeProdEnvelope.load_config(opts.fetch(:config)), repo: opts[:repo])
    path = File.join(opts[:root], WORKFLOW)
    FileUtils.mkdir_p(File.dirname(path))
    File.write(path, text)
    stdout.puts "wrote #{path}"
    vendor(opts[:root]).each { |file| stdout.puts "wrote #{file}" }
    stdout.puts "one-time repo setting (human, once): #{oidc_command(opts[:repo])}"
    0
  rescue Refused, ChangeProdEnvelope::Invalid, OptionParser::ParseError, KeyError => e
    stderr.puts "[cf-prod] refused: #{e.message}"
    1
  end

  def source_root = File.expand_path(__dir__)

  def vendor(root)
    VENDORED.map do |name|
      target = File.join(root, SCRIPTS, name)
      FileUtils.mkdir_p(File.dirname(target))
      FileUtils.cp(File.join(source_root, name), target)
      target
    end
  end

  def stale_vendored(root)
    VENDORED.reject do |name|
      target = File.join(root, SCRIPTS, name)
      File.exist?(target) && File.read(target) == File.read(File.join(source_root, name))
    end
  end

  def check(opts, stdout, stderr)
    path = File.join(opts[:root], WORKFLOW)
    unless File.exist?(path) && !tampered?(File.read(path))
      stderr.puts "[cf-prod] #{WORKFLOW} is missing or was edited by hand; regenerate it"
      return 1
    end
    stale = stale_vendored(opts[:root])
    unless stale.empty?
      stderr.puts "[cf-prod] vendored scripts are missing or differ from this toolkit: #{stale.join(', ')}; regenerate"
      return 1
    end
    stdout.puts "#{WORKFLOW} and its vendored scripts are unchanged since generation"
    0
  end
end

exit(ChangeProdRunnerGen.run(ARGV)) if __FILE__ == $PROGRAM_NAME
