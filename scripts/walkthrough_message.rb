# frozen_string_literal: true

require 'base64'
require 'digest'
require 'erb'
require 'fileutils'
require 'json'
require_relative 'walkthrough_compose'

# The message scene kind: a simulated inbound notification or message for
# walkthroughs. Nothing is sent or received. An sms shows as a lock screen
# banner or a thread (with an optional typed reply); an email as an inbox row
# or the open message (with an optional call to action into the next scene).
# Markup and styles are versioned templates in
# skills/walkthrough/reference/compose/; colors and type come from the
# project's tokens when it has them.
#
# A live board films the page in the live browser like a compose scene. A
# prototype board renders it to a screen file once (this script's CLI),
# optionally inside a project shell, so it is captured like any other screen
# and keeps the project's own device frame.
module WalkthroughMessage
  KIND = 'message'
  VIEWS = { 'sms' => %w[lock_banner thread], 'email' => %w[inbox open] }.freeze
  FIELDS = %w[channel view from to subject body preview time clock date app others cta shell].freeze
  OTHER_FIELDS = %w[from subject preview time].freeze
  TEMPLATE_VERSION = 1
  SLOT = '<div data-cf-message></div>'
  GENERATED = '<!-- generated by walkthrough_message.rb from the storyboard; edit the scene, not this file -->'
  ICON_TYPES = { '.svg' => 'image/svg+xml', '.png' => 'image/png', '.jpg' => 'image/jpeg', '.jpeg' => 'image/jpeg', '.webp' => 'image/webp' }.freeze

  module_function

  def message?(scene) = scene['kind'] == KIND

  # A message scene with a screen file is a prototype screen; without one it
  # is filmed in the live browser.
  def realtime?(scene) = message?(scene) && !scene.key?('screen')

  # -- validation ------------------------------------------------------------

  # `ctx` is { orders: { id => order }, board:, root: (the project dir) }.
  def errors(scene, ctx)
    spec = scene['message']
    return [ 'message is required for a message scene' ] unless spec.is_a?(Hash)

    unknown = spec.keys - FIELDS
    errs = unknown.empty? ? [] : [ "message has unknown keys: #{unknown.join(', ')}" ]
    views = VIEWS[spec['channel']]
    return errs << "message.channel must be one of #{VIEWS.keys.join(', ')}" unless views
    return errs << "message.view for #{spec['channel']} must be one of #{views.join(', ')}" unless views.include?(spec['view'])

    errs.concat(text_errors(spec))
    errs.concat(view_errors(spec, scene, ctx[:orders]))
    errs.concat(app_errors(spec['app'], ctx[:root]))
    errs.concat(screen_errors(scene, ctx[:board] || {}, ctx[:root]))
  end

  def text_errors(spec)
    errs = []
    %w[from body].each { |k| errs << "message.#{k} is required" if spec[k].to_s.strip.empty? }
    errs << 'message.subject is required for an email' if spec['channel'] == 'email' && spec['subject'].to_s.strip.empty?
    (FIELDS - %w[channel view app others cta shell]).each do |k|
      errs << "message.#{k} must be a string" if spec.key?(k) && !spec[k].is_a?(String)
    end
    errs
  end

  def view_errors(spec, scene, orders)
    errs = []
    errs << 'message.clock and message.date apply only to lock_banner' if spec['view'] != 'lock_banner' && (spec.key?('clock') || spec.key?('date'))
    errs.concat(others_errors(spec))
    errs.concat(cta_errors(spec, scene, orders))
  end

  def others_errors(spec)
    return [] unless spec.key?('others')
    return [ 'message.others applies only to inbox' ] unless spec['view'] == 'inbox'

    ok = spec['others'].is_a?(Array) && spec['others'].all? { |o| o.is_a?(Hash) && (o.keys - OTHER_FIELDS).empty? && o['from'].is_a?(String) }
    ok ? [] : [ "message.others is a list of { #{OTHER_FIELDS.join(', ')} } with from required" ]
  end

  # A call to action lands on the very next scene, so the tap and the screen
  # it opens read as one motion.
  def cta_errors(spec, scene, orders)
    cta = spec['cta']
    return [] if cta.nil?
    return [ 'message.cta applies only to an open email' ] unless spec['view'] == 'open'
    return [ 'message.cta is { label, to_scene }' ] unless cta.is_a?(Hash) && cta['label'].is_a?(String) && !cta['label'].strip.empty?

    to = orders[cta['to_scene']]
    to == scene['order'].to_i + 1 ? [] : [ "message.cta.to_scene #{cta['to_scene'].inspect} must be the next scene" ]
  end

  def app_errors(app, root)
    return [] if app.nil?
    return [ 'message.app is { name, icon }' ] unless app.is_a?(Hash) && (app.keys - %w[name icon]).empty?

    icon = app['icon']
    return [] if icon.nil?
    return [ "message.app.icon must be one of #{ICON_TYPES.keys.join(', ')}" ] unless ICON_TYPES.key?(File.extname(icon.to_s).downcase)
    return [ "message.app.icon #{icon} does not exist" ] if root && !File.file?(File.join(root, icon.to_s))

    []
  end

  # A prototype message screen must match what this script would write.
  def screen_errors(scene, board, root)
    html = scene.dig('screen', 'html')
    shell = scene.dig('message', 'shell')
    return [ 'message.shell needs a screen.html to render into' ] if shell && html.nil?
    return [] if html.nil? || root.nil?
    return [ "message.shell #{shell} has no #{SLOT}" ] if shell && !File.read(File.join(root, shell)).include?(SLOT)

    path = File.join(root, html)
    current = File.file?(path) && File.read(path) == screen(scene['message'], root: root, board: board, out: html)
    current ? [] : [ "#{html} is stale; run walkthrough_message.rb on the storyboard" ]
  rescue Errno::ENOENT => e
    [ "message.shell: #{e.message}" ]
  end

  # -- rendering ---------------------------------------------------------------

  def esc(text) = ERB::Util.html_escape(text.to_s)

  def initials(name) = name.to_s.split.first(2).map { |w| w[0] }.join.upcase

  def app_name(spec, board) = spec.dig('app', 'name') || board['title'] || 'Messages'

  def icon_html(spec, board, root)
    icon = spec.dig('app', 'icon')
    if icon && root
      data = Base64.strict_encode64(File.binread(File.join(root, icon)))
      return %(<img class="cfm-icon" alt="" src="data:#{ICON_TYPES.fetch(File.extname(icon).downcase)};base64,#{data}">)
    end
    %(<span class="cfm-icon" aria-hidden="true">#{esc(initials(app_name(spec, board))[0])}</span>)
  end

  def preview(spec) = spec['preview'] || spec['body'].to_s.lines.first.to_s.strip

  # Earlier rows are read and not tappable, so they are not buttons like the
  # new message in inbox.html.
  def others_html(spec)
    Array(spec['others']).map do |o|
      %(<li><div class="cfm-row"><span class="cfm-who">#{esc(o['from'])}</span><span class="cfm-muted">#{esc(o['time'])}</span>) +
        %(<span class="cfm-subj">#{esc(o['subject'])}</span><span class="cfm-snip">#{esc(o['preview'])}</span></div></li>)
    end.join("\n")
  end

  def cta_html(spec)
    cta = spec['cta']
    cta ? %(<button id="cta" class="cfm-cta" type="button">#{esc(cta['label'])}</button>) : ''
  end

  # The view fragment, filled from the spec.
  def view(spec, board: {}, root: nil)
    values = { 'from' => esc(spec['from']), 'to' => esc(spec['to'] || 'you'), 'subject' => esc(spec['subject']), 'body' => esc(spec['body']),
               'preview' => esc(preview(spec)), 'time' => esc(spec['time'] || 'now'), 'clock' => esc(spec['clock'] || '9:41'),
               'date' => esc(spec['date']), 'app' => esc(app_name(spec, board)), 'icon' => icon_html(spec, board, root),
               'initials' => esc(initials(spec['from'])), 'others' => others_html(spec), 'cta' => cta_html(spec) }
    WalkthroughCompose.fill(WalkthroughCompose.template("#{spec['view']}.html"), values)
  end

  # A full page for the live browser on one device. A project tokens.css at
  # the root is inlined so colors and type match the app.
  def page(spec, device, board: {}, root: nil)
    tokens = tokens_path(root) ? "<style>#{File.read(tokens_path(root))}</style>" : ''
    page_html(spec, device, board: board, root: root, head: tokens)
  end

  def page_html(spec, device, board:, root:, head:)
    WalkthroughCompose.fill(WalkthroughCompose.template('message_page.html'),
                            'title' => esc(app_name(spec, board)), 'head' => head, 'css' => WalkthroughCompose.template('message.css'),
                            'device' => esc(device), 'view' => view(spec, board: board, root: root),
                            'script' => WalkthroughCompose.template('message.js'))
  end

  # The prototype screen file for `out` (a path under root): the view inside
  # the project shell's slot, or a page linking the tokens.css beside `out`.
  def screen(spec, root:, board:, out:)
    shell = spec['shell']
    return "#{GENERATED}\n#{page_html(spec, 'phone', board: board, root: root, head: tokens_link(root, out))}" unless shell

    html = File.read(File.join(root, shell))
    html = html.sub(SLOT, %(<div data-cf-message>#{view(spec, board: board, root: root)}</div>))
    html = html.sub('</head>', "<style>#{WalkthroughCompose.template('message.css')}</style></head>")
    html = html.sub('</body>', "<script>#{WalkthroughCompose.template('message.js')}</script></body>")
    "#{GENERATED}\n#{html}"
  end

  def tokens_link(root, out)
    File.file?(File.join(root, File.dirname(out), 'tokens.css')) ? '<link rel="stylesheet" href="tokens.css">' : ''
  end

  # Writes every prototype message screen; returns the paths written.
  def write_screens(board, root)
    board.fetch('scenes', []).select { |s| message?(s) && s.dig('screen', 'html') }.map do |scene|
      out = scene.dig('screen', 'html')
      path = File.join(root, out)
      FileUtils.mkdir_p(File.dirname(path))
      File.write(path, screen(scene['message'], root: root, board: board, out: out))
      out
    end
  end

  # Key material for a live message scene.
  def material(scene, root)
    spec = scene['message']
    icon = spec.dig('app', 'icon') && root && File.join(root, spec.dig('app', 'icon'))
    { spec: spec, template: TEMPLATE_VERSION, icon: digest(icon), tokens: digest(tokens_path(root)) }
  end

  def tokens_path(root)
    path = root && File.join(root, 'tokens.css')
    path if path && File.file?(path)
  end

  def digest(path) = path && File.file?(path) ? Digest::SHA256.file(path).hexdigest : nil

  private_class_method :text_errors, :view_errors, :others_errors, :cta_errors, :app_errors, :screen_errors, :esc, :initials,
                       :app_name, :icon_html, :preview, :others_html, :cta_html, :page_html, :tokens_link, :tokens_path, :digest
end

if __FILE__ == $PROGRAM_NAME
  path = ARGV[0] || abort('usage: walkthrough_message.rb walkthrough/<slug>/storyboard.json')
  root = File.dirname(File.expand_path(path))
  WalkthroughMessage.write_screens(JSON.parse(File.read(path)), root).each { |out| puts "wrote #{out}" }
end
